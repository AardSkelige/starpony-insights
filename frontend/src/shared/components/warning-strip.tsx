import type * as React from "react"
import { TriangleAlert } from "lucide-react"

/**
 * Предупреждение полосой — между фильтрами и содержимым страницы.
 *
 * **Полосой, а не подсказкой по наведению.** Подсказку открывают, уже приняв
 * решение по числу; здесь оговорка обязана попасться на глаза раньше самого
 * числа. Единственное место страницы, где предупреждение не свёрнуто.
 *
 * Переехало в `shared/`, когда понадобилось второму разделу: «Прибыльность»
 * оговаривает комиссию площадок, «Расчёт производства» — неснижаемый остаток.
 * Текст разный, вид обязан быть один: две полосы, отличающиеся оттенком
 * или отступом, читаются как два разных по важности сообщения.
 *
 * **Не показывается без повода.** Пустое предупреждение перестают читать,
 * и вместе с ним перестают читать все остальные, — поэтому решение
 * «показывать или нет» принимает вызывающий, а не эта обёртка.
 */
export function WarningStrip({ children }: { children: React.ReactNode }) {
  return (
    <div className="flex items-start gap-3 rounded-lg border border-warning/40 bg-warning/10 px-4 py-3 text-sm">
      <TriangleAlert aria-hidden className="mt-0.5 size-4 shrink-0 text-warning" />
      {/* `min-w-0` обязателен: без него длинный текст распирает флекс-родителя
          и уводит вбок всю страницу, а не переносится (`DESIGN.md` §15). */}
      <p className="min-w-0">{children}</p>
    </div>
  )
}
