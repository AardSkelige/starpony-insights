import type * as React from "react"

import type { Screen } from "@/shared/hooks/use-screen"

/**
 * Колонка описывается данными, а не разметкой.
 *
 * Главное здесь — `hideOn`: на каком экране колонка прячется. Решение
 * записывается рядом с колонкой, а не прячется в CSS, потому что «почему
 * на ноутбуке нет колонки Доля» — вопрос к описанию таблицы, а не к таблице.
 */
export type Column<Row> = {
  key: string
  label: string
  /** Что показать в ячейке. Форматирование живёт здесь, а не в данных. */
  render: (row: Row) => React.ReactNode
  /**
   * Сырое значение ячейки для сравнения после ручного обновления.
   *
   * Отдельно от `render`: JSX сравнивать нельзя, а ключ колонки не обязан
   * совпадать с полем ответа (`revenue` показывает `revenue_kopecks`).
   */
  changeValue: (row: Row) => unknown
  /** Выравнивание вправо и табличные цифры — для всего, что считают. */
  numeric?: boolean
  /** Выделение первой колонки: по ней взгляд находит строку. */
  strong?: boolean
  /** С какой ширины колонка исчезает. */
  hideOn?: Screen[]
  /** Формула расчётного числа — значок в заголовке колонки. */
  explain?: React.ReactNode
  /**
   * Имя сортировки на сервере. Без него колонка не сортируется вовсе —
   * так исключаются те, по которым сортировка бессмысленна или её нет в API.
   */
  sortKey?: string
  /** Подпись в карточке на телефоне, если «Наименование» там ни к чему. */
  cardLabel?: string
}

/**
 * Итог по колонке. Задаётся ключом, а не позицией: подвал, собранный руками
 * из шести ячеек, разъедется с таблицей на первой же скрытой колонке.
 */
export type Totals = {
  /** Подпись в первой колонке и в карточке на телефоне. */
  label: React.ReactNode
  values: Record<string, React.ReactNode>
}

/**
 * Высоты страницы на выбор. «Показать ещё» здесь не подходит: по таблице
 * ищут конкретный товар и сортируют, а лента с дозагрузкой ломает и то,
 * и другое — до нужной строки приходится долистывать заново.
 */
export const PAGE_SIZES = [10, 25, 50, 100] as const
export const DEFAULT_PAGE_SIZE = 10

/** Как сейчас отсортировано: имя поля и направление. */
export type Sort = { key: string; desc: boolean }

export function visibleColumns<Row>(
  columns: Column<Row>[],
  screen: Screen
): Column<Row>[] {
  return columns.filter((column) => !column.hideOn?.includes(screen))
}
