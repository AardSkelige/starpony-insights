import { WarningStrip } from "@/shared/components/warning-strip"
import type { ConsignmentShare } from "@/shared/lib/consignment"
import { formatMoney, formatShare } from "@/shared/lib/format"

/**
 * Оговорка про товар на реализации — одна на два раздела.
 *
 * **По договору комиссии отгрузка не продажа.** Товар уходит комиссионеру
 * на склад и становится продажей с приходом отчёта комиссионера; до этого
 * он может вернуться. МойСклад считает так же — поэтому «Прибыльность»
 * и «Товары в отгрузках» расходятся. Обе цифры верны, но без пометки первая
 * читается как заработанное.
 *
 * **Число здесь — не размер расхождения, и говорить так нельзя.** Полоса
 * показывает всю реализацию **показанной выборки**, а расходятся страницы
 * на её непокрытую отчётами часть и притом за всё время: на боевых 03.09
 * это 452 696 ₽ против 281 126 ₽. Само вычитание живёт в «Сводке и охвате
 * расчёта», где у него есть место объяснить, почему периода у него нет.
 *
 * Опасность не умозрительная: у «Точки продаж» — крупнейшего канала —
 * 87 % выручки это реализация, у Telegram 97 %. Вывод «канал приносит
 * больше всех» держится на складе комиссионера.
 *
 * В `shared/`, потому что понадобилась второму разделу: у «Каналов продаж»
 * и «Товаров в отгрузках» вопрос разный, а оговорка одна — и разойтись
 * она не имеет права.
 */
export function ConsignmentNote({ share }: { share: ConsignmentShare }) {
  // Реализации нет — оговорки нет. Предупреждение без повода перестают
  // читать, и вместе с ним перестают читать все остальные.
  if (share.consignment_kopecks <= 0) return null

  return (
    <WarningStrip>
      <span className="font-medium">
        {formatMoney(share.consignment_kopecks)} из показанного —{" "}
        {formatShare(share.fraction)} — товар на реализации.
      </span>{" "}
      <span className="text-muted-foreground">
        По договору комиссии он отгружен, но продажей становится только
        с приходом отчёта комиссионера — до этого покупатель за него не платил
        и может вернуть. Здесь он в выручке уже учтён целиком, на
        «Прибыльности» — только та часть, что подтверждена отчётами; поэтому
        страницы и расходятся, и обе правы.
      </span>
    </WarningStrip>
  )
}
