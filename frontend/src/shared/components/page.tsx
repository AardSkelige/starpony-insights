import * as React from "react"

/**
 * Каркас страницы раздела: шапка → фильтры → сводка → содержимое.
 *
 * Порядок фиксирован для всех десяти разделов — не ради единообразия ради
 * себя, а потому что человек за день открывает три-четыре страницы и не должен
 * каждый раз искать, где здесь кнопка обновления.
 */
export function Page({ children }: { children: React.ReactNode }) {
  // `min-w-0` обязателен, хотя ничего не задаёт на глаз. Без него ребёнок
  // флекс-контейнера имеет `min-width: auto` и распирает родителя своим
  // содержимым — то есть таблица шире экрана уводит вбок **всю страницу**,
  // вместе с шапкой и фильтрами, вместо того чтобы прокручиваться внутри
  // своей рамки. `overflow-x-auto` у таблицы без этого не работает вовсе;
  // до первой колонки с нижней границей ширины это было не видно.
  return <div className="flex min-w-0 flex-1 flex-col gap-4">{children}</div>
}

/**
 * Фильтры страницы.
 *
 * На телефоне — столбиком во всю ширину, прямо на странице. Раньше они
 * прятались в выдвижную панель по кнопке «Фильтры», и это оказалось ошибкой:
 * чтобы найти позицию, приходилось нажать кнопку, дождаться панели, ввести
 * запрос и закрыть её — четыре действия там, где ожидается одно.
 *
 * На узком и широком экранах — ряд, как было.
 */
export function Toolbar({ children }: { children: React.ReactNode }) {
  return (
    <div className="flex flex-col gap-2 sm:flex-row sm:flex-wrap sm:items-center">
      {children}
    </div>
  )
}
