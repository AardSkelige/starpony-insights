import { cn } from "@/shared/lib/utils"
import { Tooltip, TooltipContent, TooltipTrigger } from "@/shared/ui/tooltip"

export type Bar = {
  key: string
  label: string
  /** Длина полосы. Доля считается от наибольшего значения в списке. */
  value: number
  /** Что показать у конца полосы. */
  display: string
  /** Что показать по наведению — второе измерение, не влезшее в подпись. */
  hint?: string
  /**
   * Второе число у конца полосы: доля, процент, разница.
   *
   * Приглушено и уже основного: полоса и `display` отвечают на «сколько»,
   * а это уточняет «какая часть» — читается вторым, а не наравне.
   */
  secondary?: string
  /**
   * Строки под полосой — то, чего числом не сказать.
   *
   * Появились ради комментариев заказов: «на призы на ЧР-2026 по конкуру»
   * объясняет отгрузку без оплаты лучше любой категории. Не в подсказке
   * по наведению, а на виду: ради этого текста блок и открывают.
   */
  notes?: string[]
  /**
   * Тон полосы. По умолчанию все полосы одного цвета — и это правило
   * остаётся: категории не упорядочены, и красить их значило бы второй раз
   * закодировать то, что показывает длина.
   *
   * Исключение ровно одно, и оно не про категорию, а про **надёжность
   * числа**: маржа через площадку завышена на её комиссию, которой нет
   * в учёте. Это состояние, а не имя, — поэтому берётся `warning`, цвет
   * статуса, и **всегда вместе с подписью**: цветом в одиночку такое
   * не говорят (`DESIGN.md` §1).
   */
  tone?: "default" | "warning" | "destructive"
}

/**
 * Горизонтальные полосы: сравнение величин по категориям.
 *
 * **Все полосы одного цвета.** Категории здесь номинальные — каналы продаж
 * не упорядочены и не образуют шкалу, поэтому красить каждую своим цветом
 * значило бы второй раз закодировать то, что уже показывает длина, и сжечь
 * единственный свободный канал впустую. В утверждённом макете полосы были
 * разноцветными — это как раз тот случай.
 *
 * Цвет — `primary`, а не `chart-*`. Палитра графиков различает **серии**,
 * а серия здесь одна: брать из неё слот значит объявить полосам разную
 * природу, которой у них нет.
 */
export function BarList({
  bars,
  wideLabels = false,
  multilineLabels = false,
  numbersOnHover = false,
}: {
  bars: Bar[]
  /**
   * Широкая колонка подписей.
   *
   * Не вкус, а разница в данных: названия каналов короткие («ХорсСмарт»,
   * «Точка продаж»), а имена получателей — нет («ГКФХ Торшин Валерий
   * Вячеславович»). Обрезанное имя перестаёт быть опознавательным знаком,
   * а полоса и без того длинная — отдать ей часть ширины дешевле, чем
   * потерять того, о ком строка.
   */
  wideLabels?: boolean
  /**
   * Подпись переносится на две строки вместо обрезки многоточием.
   *
   * Нужна там, где имена различаются **концом**, а не началом: пять товаров
   * канала — «Кондиционер для гривы и хвоста Табак-Ваниль 500 мл», «…
   * Кокосовое молоко 500 мл», «… Персик-Банан 500 мл» — после обрезки
   * превращаются в пять одинаковых строк «Кондиционер для гривы и х…».
   * Полоса при этом честно показывает разные величины, и список читается
   * как ошибка данных.
   *
   * Не по умолчанию: у коротких имён (каналы, поставщики) вторая строка
   * пустует и разрежает список без пользы.
   */
  multilineLabels?: boolean
  /**
   * Числа уезжают в подсказку, на виду остаются подпись и полоса.
   *
   * Список из пяти строк с суммой и долей у каждой — это таблица, которую
   * читают числами; вопрос же к нему один: **кто из них главный**. На него
   * отвечает длина, и колонка цифр рядом только соревнуется с ней за
   * внимание. Точная сумма нужна редко и достаётся наведением.
   *
   * Не по умолчанию: там, где список и есть ответ в деньгах — полосы
   * каналов над таблицей, — числа остаются на виду.
   */
  numbersOnHover?: boolean
}) {
  /**
   * Длина считается от модуля и никогда не уходит в минус.
   *
   * `width: -38%` — невалидное объявление: браузер выбрасывает его целиком,
   * и полоса, будучи блоком внутри дорожки, растягивается **во всю длину**.
   * Убыточная линейка рисовалась самой длинной в списке и читалась как
   * лучшая. Ошибка тихая: ни в консоли, ни в тестах ничего.
   *
   * Клампится здесь, а не у вызывающего: правило одно на все списки,
   * а забыть его у одного из них легко — так и вышло.
   */
  const length = (bar: Bar) => Math.max(bar.value, 0)

  const max = Math.max(...bars.map(length), 0)
  if (max <= 0) return null

  return (
    <div className="flex flex-col gap-1.5">
      {bars.map((bar) => (
        <div key={bar.key} className="flex min-w-0 flex-col gap-0.5">
        <Tooltip>
          <TooltipTrigger
            render={
              // На телефоне подпись занимает свою строку, а полоса
              // с числами переносится на следующую. В 112 точек имена,
              // различающиеся **концом**, обрезаются в неотличимые:
              // «Репеллент для лошадей Против…» дважды подряд — это
              // 500 мл и 3000 мл. Найдено снимком телефона.
              <div className="flex flex-wrap items-center gap-x-3 gap-y-1 text-sm">
                <span
                  className={cn(
                    "shrink-0 text-xs text-muted-foreground",
                    "max-sm:w-full",
                    // Ширины разные на телефоне и на большом экране.
                    // 176 точек подписи, 96 числа и 48 доли не помещаются
                    // в 390 вместе с дорожкой: полоса схлопывалась в ноль,
                    // и список превращался в таблицу без картинки.
                    // Найдено снимком телефона, а не чтением кода.
                    wideLabels ? "w-28 sm:w-44" : "w-20 sm:w-24",
                    multilineLabels
                      ? "line-clamp-2 whitespace-normal"
                      : "truncate"
                  )}
                >
                  {bar.label}
                </span>
                {/* Дорожка во всю ширину: без неё полосы не с чем сравнивать,
                    кроме друг друга, и доля от целого не читается. */}
                <span className="h-1.5 min-w-0 flex-1 overflow-hidden rounded-[3px] bg-muted">
                  <span
                    className={cn(
                      "motion-bar-reveal block h-full rounded-r-[3px]",
                      bar.tone === "warning"
                        ? "bg-warning"
                        : bar.tone === "destructive"
                          ? "bg-destructive"
                          : "bg-primary"
                    )}
                    style={{ width: `${(length(bar) / max) * 100}%` }}
                  />
                </span>
                {/* Ширина под самое длинное, что сюда попадает, — денежную
                    сумму «23 350,00 ₽». Колонка чисел обязана выравниваться
                    по правому краю, поэтому ширина фиксированная: подгонка
                    по содержимому дала бы рваный столбец. */}
                {numbersOnHover ? null : (
                  <>
                    <span className="w-20 shrink-0 text-right text-xs whitespace-nowrap tabular-nums sm:w-24">
                      {bar.display}
                    </span>
                    {bar.secondary ? (
                      <span className="w-11 shrink-0 text-right text-xs text-muted-foreground tabular-nums sm:w-12">
                        {bar.secondary}
                      </span>
                    ) : null}
                  </>
                )}
              </div>
            }
          />
          {/* Подсказка собирает то, чего нет на виду. Со спрятанными числами
              она обязательна — иначе точную сумму негде посмотреть вовсе. */}
          {numbersOnHover || bar.hint ? (
            <TooltipContent>
              {numbersOnHover
                ? [bar.display, bar.secondary, bar.hint].filter(Boolean).join(" · ")
                : bar.hint}
            </TooltipContent>
          ) : null}
        </Tooltip>
        {bar.notes?.length ? (
          <div className="flex min-w-0 flex-col gap-0.5 pb-1">
            {bar.notes.map((note) => (
              // Текст переносится целиком, а не обрезается: «Лена: на призы
              // на ЧР-2026 по конкуру. + ПАКЕТЫ. + ОТКРЫТКИ» после обрезки
              // теряет ровно ту часть, ради которой его и читают.
              <p key={note} className="text-xs whitespace-normal text-muted-foreground">
                {note}
              </p>
            ))}
          </div>
        ) : null}
        </div>
      ))}
    </div>
  )
}
