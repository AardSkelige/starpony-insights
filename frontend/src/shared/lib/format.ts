/**
 * Приведение чисел учёта к виду, который читает человек.
 *
 * Всё, что приходит с сервера, приходит в единицах хранения: деньги — целыми
 * копейками, удельные величины и количества — строками Decimal. Рубли,
 * проценты и разделители разрядов появляются только здесь: перевести их
 * раньше значит потерять знаки там, где они решают, сойдётся ли с учётом.
 */

const RU = "ru-RU"

/**
 * Время показывается московским, а не по часам машины.
 *
 * Учёт ведётся в Москве, и «данные на 14:32» должно значить московские 14:32
 * — иначе сотрудник в командировке увидит время, не совпадающее ни с чем
 * в МойСкладе. Пояс здесь же делает форматирование предсказуемым: без него
 * тот же тест на машине разработчика и на сервере сборки даёт разный ответ.
 */
const TIMEZONE = "Europe/Moscow"

/** Неразрывный пробел перед знаком рубля: «231 530,38 ₽» не переносится. */
const NBSP = " "

const money = new Intl.NumberFormat(RU, {
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
})

const percent = new Intl.NumberFormat(RU, {
  minimumFractionDigits: 1,
  maximumFractionDigits: 1,
})

/** Деньги: из целых копеек в рубли. Копейки — целое число, дроби в них не бывает. */
export function formatMoney(kopecks: number): string {
  return `${money.format(kopecks / 100)}${NBSP}₽`
}

/**
 * Цена за единицу: приходит строкой Decimal в копейках и бывает дробной.
 *
 * **Знаков столько, чтобы показанная цена, умноженная на количество, давала
 * показанную сумму.** Двух знаков для этого мало: вода стоит 0,025 ₽ за грамм,
 * округляется до «0,03», и 1 324 150 г × 0,03 даёт 39 724 ₽ вместо
 * 33 103,76 ₽ — расхождение в 20 %, которое человек находит калькулятором
 * и списывает на расчёт. Цен дешевле рубля в учёте 51 из 188.
 *
 * Правило: не меньше двух знаков и не меньше трёх значащих цифр. Дорогая
 * позиция остаётся с копейками («15 500,00 ₽»), дешёвое сырьё получает
 * столько знаков, сколько ему нужно («0,0250 ₽»).
 *
 * Округляется только на экране — в расчёте участвует то, что пришло.
 */
export function formatUnitPrice(kopecks: string | null): string {
  if (kopecks === null) return "—"

  const rubles = Number(kopecks) / 100
  return `${new Intl.NumberFormat(RU, {
    minimumFractionDigits: 2,
    maximumFractionDigits: significantDigits(rubles),
  }).format(rubles)}${NBSP}₽`
}

/**
 * Сколько знаков после запятой нужно, чтобы в числе осталось три значащих.
 *
 * `floor` от десятичного логарифма — позиция первой значащей цифры, и три
 * знака от неё дают нужную точность на любом порядке: 0,025 получает четыре
 * знака, 0,216 — три, 8 886,9 — ни одного. Потолок в шесть знаков —
 * разрядность самого поля в учёте: больше него значащих цифр не приходит.
 *
 * `floor` — минимум знаков. У цены он равен двум: копейки показываются даже
 * там, где они нули, потому что деньги так читают. У средней величины нулю:
 * «8 887 г в день» — среднее за сто сорок девять дней, и дробная часть
 * в нём означала бы точность, которой нет.
 */
function significantDigits(value: number, floorDigits = 2): number {
  const size = Math.abs(value)
  if (size === 0) return floorDigits
  return Math.min(
    Math.max(2 - Math.floor(Math.log10(size)), floorDigits),
    6
  )
}

/**
 * Количество: строка Decimal с тремя знаками.
 *
 * Хвост из нулей убирается — «430» вместо «430.000». Дробная часть
 * сохраняется там, где она есть: килограммы и граммы сырья дробные,
 * и «0,5 кг», показанные как «1 кг», расходятся с учётом вдвое.
 */
export function formatQuantity(value: string, uom?: string): string {
  const number = Number(value)
  const text = new Intl.NumberFormat(RU, { maximumFractionDigits: 3 }).format(number)
  return uom ? `${text}${NBSP}${uom}` : text
}

/**
 * Средняя величина — количество в единицу времени.
 *
 * Отличается от `formatQuantity` тем, что **не показывает точности,
 * которой нет**. Дневной расход получен делением: «8 886,914 г в день»
 * читается как измеренное число, хотя это среднее за сто сорок девять дней,
 * и три знака в нём — шум. При этом у мелкого сырья те же три знака
 * необходимы: расход бывает 0,0016 г в день.
 *
 * Правило то же, что у цены: не меньше трёх значащих цифр, но и не больше.
 */
export function formatRate(value: string, uom?: string): string {
  const text = new Intl.NumberFormat(RU, {
    maximumFractionDigits: significantDigits(Number(value), 0),
  }).format(Number(value))
  return uom ? `${text}${NBSP}${uom}` : text
}

/**
 * Доля единицы в проценты: 0.1894 → «18,9 %».
 *
 * **Крошечная доля не превращается в ноль.** Одного знака мало: 0,00005
 * округляется до «0,0 %», и строка читается как «не участвует» — а материал
 * участвует, просто мало. На боевых данных таких строк 90 из 439 по трём
 * страницам, и у самой мелкой доля 0,000047 %.
 *
 * Показывается «< 0,1 %»: это честное «меньше десятой процента», в отличие
 * от нуля, который утверждает отсутствие. Добавлять знаки взамен нельзя —
 * «0,000047 %» в колонке нечитаемо и ничего не решает.
 *
 * Ноль остаётся нулём: доля действительно нулевая — это факт, а не потеря.
 */
export function formatShare(share: string | null): string {
  if (share === null) return "—"

  const value = Number(share) * 100
  if (value > 0 && value < 0.05) return `<${NBSP}0,1${NBSP}%`
  return `${percent.format(value)}${NBSP}%`
}

/**
 * Отметка свежести данных — «данные на 14:32».
 *
 * Если синхронизация прошла не сегодня, показывается и дата: иначе «14:32»
 * у вчерашних данных читается как «только что», а это ровно та ошибка,
 * ради которой отметка и существует.
 */
export function formatSyncedAt(iso: string | null, now: Date = new Date()): string {
  if (!iso) return "данные ещё не загружались"

  const moment = new Date(iso)
  const time = moment.toLocaleTimeString(RU, {
    hour: "2-digit",
    minute: "2-digit",
    timeZone: TIMEZONE,
  })

  // Сравниваются московские календарные дни, а не дни по часам машины:
  // иначе у человека западнее Москвы вчерашняя синхронизация показалась бы
  // сегодняшней, и «14:32» прочиталось бы как «только что».
  const sameDay = moscowDay(moment) === moscowDay(now)

  if (sameDay) return `данные на ${time}`

  const date = moment.toLocaleDateString(RU, {
    day: "2-digit",
    month: "2-digit",
    timeZone: TIMEZONE,
  })
  return `данные на ${date}, ${time}`
}

/** Календарный день в Москве — «2026-08-27», для сравнения дат. */
function moscowDay(date: Date): string {
  return date.toLocaleDateString("en-CA", { timeZone: TIMEZONE })
}

/**
 * Дата целиком: «17.08.2026».
 *
 * Нужна там, где год решает, верить ли числу: цена закупки могла быть
 * зафиксирована в прошлом году, и «17.08» от «17.08 этого года» не отличить.
 */
export function formatDate(iso: string): string {
  return new Date(iso).toLocaleDateString(RU, {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    timeZone: TIMEZONE,
  })
}

/**
 * День и месяц: «17.08». Для списков, где год очевиден из выбранного периода.
 *
 * Пояс задан, как и везде здесь: без него дата документа, снятая в 23:40
 * по Москве, у человека западнее показалась бы предыдущим днём — и строка
 * в списке отгрузок не сошлась бы с самим документом в учёте.
 */
export function formatDayMonth(iso: string): string {
  return new Date(iso).toLocaleDateString(RU, {
    day: "2-digit",
    month: "2-digit",
    timeZone: TIMEZONE,
  })
}
