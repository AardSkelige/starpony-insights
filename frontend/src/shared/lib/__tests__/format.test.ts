import { describe, expect, it } from "vitest"

import {
  formatDate,
  formatDayMonth,
  formatMoney,
  formatQuantity,
  formatShare,
  formatSyncedAt,
  formatRate,
  formatUnitPrice,
} from "@/shared/lib/format"

/** Неразрывный пробел: им отделяются и разряды, и знак единицы. */
const NB = " "

describe("formatMoney", () => {
  it("переводит копейки в рубли и разбивает разряды", () => {
    // Выручка по всем отгрузкам за пять месяцев — с ней сверяют итог.
    expect(formatMoney(122265995)).toBe(`1${NB}222${NB}659,95${NB}₽`)
  })

  it("не теряет копейки", () => {
    // 231 530,38 ₽ — выручка лидера продаж. Потерянные копейки видно сразу:
    // именно по ним сверяют итог с МойСкладом.
    expect(formatMoney(23153038)).toBe(`231${NB}530,38${NB}₽`)
  })

  it("показывает круглую сумму с двумя знаками", () => {
    expect(formatMoney(100000)).toBe(`1${NB}000,00${NB}₽`)
  })

  it("показывает ноль, а не пустоту", () => {
    expect(formatMoney(0)).toBe(`0,00${NB}₽`)
  })
})

describe("formatUnitPrice", () => {
  it("показывает дробную цену в копейках двумя знаками рубля", () => {
    // 53844,274418 копейки — средняя цена репеллента, как её отдаёт сервер.
    // Округление здесь только показное: в расчёт ушло всё, что пришло.
    expect(formatUnitPrice("53844.274418")).toBe(`538,44${NB}₽`)
  })

  it("отсутствие цены показывает прочерком, а не нулём", () => {
    // Ноль читался бы как «отдавали бесплатно», а на деле цены просто нет.
    expect(formatUnitPrice(null)).toBe("—")
  })
})

describe("formatQuantity", () => {
  it("убирает хвост нулей", () => {
    expect(formatQuantity("430.000", "шт")).toBe(`430${NB}шт`)
  })

  it("сохраняет дробную часть", () => {
    // «0,5 кг», показанные как «1 кг», расходятся с учётом вдвое.
    expect(formatQuantity("0.500", "кг")).toBe(`0,5${NB}кг`)
  })

  it("работает без единицы измерения", () => {
    expect(formatQuantity("105.000")).toBe("105")
  })
})

describe("formatShare", () => {
  it("переводит долю единицы в проценты с одним знаком", () => {
    expect(formatShare("0.18937")).toBe(`18,9${NB}%`)
  })

  it("отсутствие доли показывает прочерком", () => {
    expect(formatShare(null)).toBe("—")
  })
})

describe("formatSyncedAt", () => {
  // Пояс задан в самом форматтере, поэтому ответ одинаков и на машине
  // разработчика, и на сервере сборки, где часы стоят по UTC. Раньше эти
  // два теста проходили локально и падали в CI.
  it("сегодняшнюю синхронизацию показывает временем", () => {
    const now = new Date("2026-08-27T15:00:00+03:00")
    const synced = "2026-08-27T12:44:00+03:00"

    expect(formatSyncedAt(synced, now)).toBe("данные на 12:44")
  })

  it("считает день по московскому календарю, а не по часам машины", () => {
    // Оба момента — 27 августа по Москве, но по UTC синхронизация попадает
    // ещё в 26-е (01:00 MSK = 22:00 предыдущего дня). Сравнивай мы дни
    // по часам машины, сегодняшняя синхронизация показалась бы вчерашней —
    // с датой, которой человек не ждёт.
    const now = new Date("2026-08-27T22:00:00+03:00")
    const synced = "2026-08-27T01:00:00+03:00"

    expect(formatSyncedAt(synced, now)).toBe("данные на 01:00")
  })

  it("вчерашнюю показывает вместе с датой", () => {
    // Без даты «12:44» у вчерашних данных читается как «только что» —
    // ровно та ошибка, ради которой отметка и существует.
    const now = new Date("2026-08-27T15:00:00+03:00")
    const synced = "2026-08-26T12:44:00+03:00"

    expect(formatSyncedAt(synced, now)).toBe("данные на 26.08, 12:44")
  })

  it("говорит прямо, если синхронизации не было", () => {
    expect(formatSyncedAt(null)).toBe("данные ещё не загружались")
  })
})

describe("даты", () => {
  it("день и месяц — из даты периода", () => {
    expect(formatDayMonth("2026-04-01")).toBe("01.04")
  })

  it("день и месяц — из отметки документа", () => {
    expect(formatDayMonth("2026-08-17T14:32:00+03:00")).toBe("17.08")
  })

  it("поздний вечер по Москве остаётся тем же днём", () => {
    // Документ, проведённый в 23:40 по Москве, у человека западнее показался
    // бы предыдущим днём — и строка в списке отгрузок не сошлась бы
    // с самим документом в учёте.
    expect(formatDayMonth("2026-08-17T23:40:00+03:00")).toBe("17.08")
  })

  it("полная дата несёт год", () => {
    // Цену могли зафиксировать в прошлом году, и «17.08» от «17.08 этого
    // года» не отличить — а от этого зависит, верить ли числу.
    expect(formatDate("2025-08-17T10:00:00+03:00")).toBe("17.08.2025")
  })
})

describe("цена за единицу показывает значащие знаки", () => {
  it("дорогая позиция остаётся с копейками", () => {
    expect(formatUnitPrice("1550000")).toBe(`15${NB}500,00${NB}₽`)
    expect(formatUnitPrice("3105")).toBe(`31,05${NB}₽`)
  })

  it("дешёвое сырьё получает столько знаков, сколько ему нужно", () => {
    // Вода: 0,025 ₽ за грамм. Двумя знаками это «0,03», и умножение
    // на 1 324 150 г даёт 39 724 ₽ вместо 33 103,76 — расхождение 20 %,
    // которое человек находит калькулятором и списывает на расчёт.
    // Хвостовые нули не добиваются: «0,025» — это те же три значащие
    // цифры, а лишний ноль только удлиняет колонку.
    expect(formatUnitPrice("2.5")).toBe(`0,025${NB}₽`)
    expect(formatUnitPrice("8.983333")).toBe(`0,0898${NB}₽`)
    expect(formatUnitPrice("21.58")).toBe(`0,216${NB}₽`)
  })

  it("показанная цена умножается в показанную сумму", () => {
    // Главная проверка: экран открывают, чтобы складывать и умножать.
    const shown = Number(
      formatUnitPrice("2.5").replace(/[^\d,]/g, "").replace(",", ".")
    )
    expect(1_324_150.25 * shown).toBeCloseTo(33_103.76, 0)
  })

  it("ноль и отсутствие цены не ломают расчёт знаков", () => {
    expect(formatUnitPrice("0")).toBe(`0,00${NB}₽`)
    expect(formatUnitPrice(null)).toBe("—")
  })
})

describe("средняя величина не показывает точности, которой нет", () => {
  it("крупный расход идёт целым числом", () => {
    // «8 886,914 г в день» читается как измеренное число, хотя это среднее
    // за сто сорок девять дней, и три знака в нём — шум.
    expect(formatRate("8886.914429530201", "г")).toBe(`8${NB}887${NB}г`)
    expect(formatRate("923.4899", "г")).toBe(`923${NB}г`)
  })

  it("мелкий расход сохраняет значащие цифры", () => {
    // У мелкого сырья те же знаки необходимы: бывает 0,0016 г в день.
    expect(formatRate("0.001610738", "г")).toBe(`0,00161${NB}г`)
    expect(formatRate("10.53", "шт")).toBe(`10,5${NB}шт`)
  })

  it("ноль не ломает расчёт знаков", () => {
    expect(formatRate("0", "г")).toBe(`0${NB}г`)
  })
})

describe("порог значащих цифр един для цены и средней", () => {
  it("средняя между сотней и тысячей идёт без дробей", () => {
    // Отдельная ветка «больше ста — целое» была мёртвой: формула даёт
    // тот же ответ сама. Проверка стережёт её отсутствие.
    expect(formatRate("150.49", "г")).toBe(`150${NB}г`)
    expect(formatRate("99.87", "г")).toBe(`99,9${NB}г`)
  })

  it("цена никогда не теряет копеек, средняя — теряет", () => {
    // Деньги читают с копейками даже там, где они нули. Среднее — нет.
    expect(formatUnitPrice("1000")).toBe(`10,00${NB}₽`)
    expect(formatRate("10", "г")).toBe(`10${NB}г`)
  })
})

describe("крошечная доля не превращается в ноль", () => {
  it("меньше десятой процента показывается как «< 0,1 %»", () => {
    // «0,0 %» читается как «не участвует», а материал участвует — просто
    // мало. Таких строк 90 из 439 по трём страницам.
    expect(formatShare("0.0000005")).toBe(`<${NB}0,1${NB}%`)
    expect(formatShare("0.0004")).toBe(`<${NB}0,1${NB}%`)
  })

  it("настоящий ноль остаётся нулём", () => {
    // Нулевая доля — это факт учёта, а не потеря при округлении.
    expect(formatShare("0")).toBe(`0,0${NB}%`)
  })

  it("обычные доли не трогаются", () => {
    expect(formatShare("0.1894")).toBe(`18,9${NB}%`)
    expect(formatShare("1")).toBe(`100,0${NB}%`)
    // Граница: 0,05 % округляется до «0,1 %» и порогом не считается.
    expect(formatShare("0.0005")).toBe(`0,1${NB}%`)
  })

  it("неизвестная доля остаётся прочерком", () => {
    // Прочерк и «< 0,1 %» — разные утверждения: «не знаем» против «мало».
    expect(formatShare(null)).toBe("—")
  })
})
