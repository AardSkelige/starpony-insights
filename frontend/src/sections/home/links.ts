import type { Home } from "@/sections/home/api"

/**
 * Куда ведут плитки — вместе с периодом, за который они посчитаны.
 *
 * **Период обязателен, а не украшение.** Плитка говорит «в августе маржа
 * 6,3 %», раздел по умолчанию открывается за свой период — и человек видит
 * другой список с другими числами. Это тот же дефект «соседние числа
 * о разных множествах» (`DESIGN.md` §8), только разнесённый на два экрана,
 * где заметить его ещё труднее: обе страницы по отдельности правы.
 *
 * Имена параметров — `from` и `to`, как их читает `use-table-params.ts`.
 * Второго списка имён в проекте нет, и заводить его здесь нельзя: разъедутся
 * молча, а ссылка при этом останется рабочей — просто откроет не тот период.
 */
export function withMonth(
  path: string,
  period: Home["period"],
  /**
   * Сортировка, с которой открыть раздел. Ключ в адресной строке — `sort`,
   * а не `ordering`: последнее имя носит параметр **запроса к API**, и они
   * не совпадают. Первая версия ссылки писала `ordering=margin`, страница
   * его молча игнорировала и открывалась своей сортировкой по умолчанию —
   * то есть ссылка работала, а обещанного не показывала.
   */
  sort?: string
): string {
  const params = new URLSearchParams()
  params.set("from", period.first)
  params.set("to", period.last)
  if (sort) params.set("sort", sort)
  return `${path}?${params.toString()}`
}
