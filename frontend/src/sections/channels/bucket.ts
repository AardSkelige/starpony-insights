/**
 * Как назвать промежуток времени.
 *
 * Живёт у раздела, а не в `shared/`: тем же занят `timeline.tsx` у отгрузок,
 * но переезжать пока нечему — там свои формы того же правила, и общей эту
 * пару делает только повод, а не вызов. Переедет, когда понадобится
 * третьему.
 */

const MONTHS = [
  "январь", "февраль", "март", "апрель", "май", "июнь",
  "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь",
]

/** Дата коротко: «29.06.26». */
export function formatDay(iso: string): string {
  const [year, month, day] = iso.split("-")
  return `${day}.${month}.${year.slice(2)}`
}

/**
 * Имя одного столбика.
 *
 * **Промежуток, а не его начало.** «29.06.26» под подписью «столбик —
 * неделя» читается как один день — так и вышло при первом показе на соседней
 * странице. Неделя называет обе границы, месяц — своё имя, и только день
 * остаётся одной датой, потому что он ею и является.
 */
export function bucketLabel(start: string, end: string, step: string): string {
  if (step === "day") return formatDay(start)
  if (step === "month") {
    const [year, month] = start.split("-")
    return `${MONTHS[Number(month) - 1]} ${year}`
  }
  return `${formatDay(start)} – ${formatDay(end)}`
}

/**
 * Чем измерен один промежуток ряда: «промежуток — неделя».
 *
 * Не «столбик»: сервер называет так свою корзину (`api/common/timeline.py`),
 * и на странице отгрузок это верно — там столбики. Здесь ряд рисуется
 * площадью, и слово «столбик» описывало бы форму, которой нет. Сам шаг
 * по-прежнему выбирает сервер, здесь только его название.
 */
export function stepNote(step: string): string {
  if (step === "day") return "промежуток — день"
  if (step === "month") return "промежуток — месяц"
  return "промежуток — неделя"
}
