import type { Picked, ProductRow } from "@/sections/production/api"

/**
 * Что требует решения: кончается в ближайшие две недели, остаток неизвестен
 * либо уже отмечено.
 *
 * **Один список на двух потребителей** — что показать в левой колонке
 * по умолчанию и что берёт кнопка «Взять всё, что кончается». Разойдись они,
 * кнопка складывала бы в партию строки, которых на экране нет: до этого
 * она брала **все** пятьдесят семь товаров, включая спрятанные за «Показать
 * ещё — их пока хватает», и закупка считалась по партии, которую человек
 * не собирал.
 *
 * **Неизвестный остаток входит.** Кнопка «их пока хватает» обещает про
 * скрытые именно это, а про такие строки мы как раз не знаем — прятать их
 * значило бы выдать незнание за благополучие. Так же устроен список закупки.
 *
 * Порог «две недели» задаёт сервер (`coverage.CRITICAL_DAYS`) и присылает
 * готовым уровнем: пороги и текст предупреждения обязаны меняться вместе.
 */
export function runningOut(rows: ProductRow[], picked: Picked): ProductRow[] {
  return rows.filter(
    (row) =>
      row.coverage.level === "critical" ||
      row.available === null ||
      row.article in picked
  )
}
