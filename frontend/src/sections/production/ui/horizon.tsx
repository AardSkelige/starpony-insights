import { ICON_GROUP } from "@/app/layout/icon-group"
import { HORIZONS } from "@/sections/production/use-batch"
import { Explain } from "@/shared/components/explain"
import { Button } from "@/shared/ui/button"

/**
 * На сколько дней вперёд производим.
 *
 * Это и есть страховой запас, который в `PRD.md` §5.9 записан открытым
 * вопросом. Вместо числа, придуманного в коде, человек выбирает его сам
 * и сразу видит последствия: тридцать дней и девяносто дают разную партию
 * и разную закупку. Ответ на этот выбор потом получит демон, который
 * начнёт проставлять неснижаемый остаток в карточки товаров.
 *
 * Место — в ряду фильтров, потому что переключатель меняет показанные числа
 * так же, как период. Кнопка «Сбросить» его не трогает: он не сужает
 * выборку, а меняет вопрос — то же правило, что у базы расчёта
 * на «Прибыльности».
 *
 * **Обойма `ICON_GROUP`, а не `ToggleGroup` из реестра** — тот же вид, что
 * у переключателя темы в шапке. Причина записана там же и подтвердилась
 * здесь дважды: у реестрового `Toggle` наведение и выбор красятся одним
 * цветом (`hover:bg-muted` против `aria-pressed:bg-muted`), и выбранный
 * вариант неотличим от того, на который просто навели. А в склеенном виде
 * (`spacing={0}`) разделителем служит правая граница соседа, тогда как свою
 * левую реестр убирает, — и у выбранного сегмента граница слева пропадала.
 * У обоймы рамка одна, вокруг группы: разделителей нет, и терять нечего.
 */
export function Horizon({
  value,
  onChange,
}: {
  value: number
  onChange: (horizon: number) => void
}) {
  return (
    <div className="flex items-center gap-2 max-sm:h-10">
      <span className="flex items-center gap-1.5 text-sm text-muted-foreground">
        Производим на
        <Explain>
          На сколько дней вперёд делаем запас. Отсюда берётся количество
          в поле «произвести»: средние продажи в день × выбранный срок −
          то, что уже лежит на складе. Округляем вверх — половину флакона
          не варят.
        </Explain>
      </span>

      <div className={ICON_GROUP} role="group" aria-label="Горизонт производства">
        {HORIZONS.map((days) => (
          <Button
            key={days}
            // `secondary` против `ghost`: выбранный залит, остальные пустые,
            // и наведение красит их по-разному — «навёл» и «выбрал»
            // не путаются.
            variant={value === days ? "secondary" : "ghost"}
            size="icon-sm"
            aria-pressed={value === days}
            onClick={() => onChange(days)}
            // Ширина равна высоте: «15» уже «90» на пару точек, и по
            // содержимому ряд выходил разной ширины. Сорок точек
            // на телефоне — минимум, под который попадает палец
            // (`DESIGN.md` §15).
            className="max-sm:size-10"
          >
            {days}
          </Button>
        ))}
      </div>

      <span className="text-sm text-muted-foreground">дней</span>
    </div>
  )
}
