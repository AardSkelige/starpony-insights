const RU = "ru-RU"
const NBSP = " "

/**
 * Стоимость закупки — приблизительно и без копеек.
 *
 * **Точная сумма здесь была бы враньём.** Она получена умножением нехватки
 * на цену последней приёмки: «не хватает 92 425,75 г воды × 2,49 копейки».
 * Но воду не покупают граммами — её берут канистрами, и заказ округлится
 * вверх до упаковки, размер которой в учёте не хранится. Копейки в таком
 * числе изображают точность, которой нет.
 *
 * Поэтому «≈ 2 791 ₽»: порядок величины, по которому прикидывают бюджет,
 * и видно, что это прикидка. Решение 03.09 по замечанию владельца —
 * до этого страница показывала «2 790,78 ₽» и выглядела счётом.
 */
export function approxRubles(kopecks: number): string {
  const rubles = new Intl.NumberFormat(RU, { maximumFractionDigits: 0 }).format(
    kopecks / 100
  )
  return `≈${NBSP}${rubles}${NBSP}₽`
}
