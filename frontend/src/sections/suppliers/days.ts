import { withPlural } from "@/shared/lib/plural"

/**
 * Дни с правильным склонением: «7 дней», «7,5 дня».
 *
 * Отдельным файлом от компонентов, которые её зовут: файл, экспортирующий
 * и компоненты, и функции, ломает горячую перезагрузку — правка формулы
 * перезагружала бы страницу целиком вместо обновления на месте.
 *
 * Дробь бывает настоящей: медиана чётного числа значений — среднее двух
 * средних, и при 0, 0, 7 и 8 днях «3,5 дня» это честный ответ.
 */
export function formatDays(days: number): string {
  if (!Number.isInteger(days)) {
    return `${days.toLocaleString("ru-RU", { maximumFractionDigits: 1 })} дня`
  }
  return withPlural(days, "день", "дня", "дней")
}
