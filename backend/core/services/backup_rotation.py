"""Что из старых архивов можно удалить.

Единственное опасное решение во всём бэкапе: снять копию — операция без
последствий, удалить старую — необратимая. Поэтому она живёт здесь,
в тестируемом коде, а не в строке `ls -t | tail -n +15 | xargs rm`.

**Правило первое: старое не удаляется, пока новое не создано и не проверено.**
Не «скрипт отработал», а именно проверено восстановлением: пустой или
обрезанный архив создаётся так же успешно, как настоящий, и по наличию файла
их не отличить. Прогон, который упал или не прошёл проверку, не удаляет
ничего — даже если архивов накопилось вдвое больше нормы. Место кончится
заметно, тихо потерянная история — нет.

Имя архива несёт отметку времени (`starpony-2026-09-03-0330.dump`), поэтому
хронологический порядок совпадает с алфавитным. Это не совпадение, а условие:
разбор даты из имени добавил бы разбору строк право решать, что удалить.
"""

from dataclasses import dataclass

# Сколько снимков держим. Четырнадцать — две недели: столько нужно, чтобы
# заметить порчу данных, которую видно не сразу. Порог держится решением,
# а не расчётом свободного места: место кончится заметно.
DEFAULT_KEEP = 14


@dataclass(frozen=True)
class Rotation:
    """Что оставить и что удалить. Ничего не удаляет сама — только решает."""

    keep: tuple[str, ...]
    prune: tuple[str, ...]


def plan(
    existing: list[str], *, verified: bool, keep: int = DEFAULT_KEEP
) -> Rotation:
    """Решить судьбу архивов после очередного прогона.

    `existing` — все архивы в каталоге, включая только что снятый.
    `verified` — прошёл ли **этот** прогон проверку восстановлением.

    Не проверен — не удаляем ничего: единственная копия, которой можно
    доверять, может оказаться как раз самой старой.
    """
    ordered = sorted(existing, reverse=True)

    if not verified:
        return Rotation(keep=tuple(ordered), prune=())

    return Rotation(keep=tuple(ordered[:keep]), prune=tuple(ordered[keep:]))
