"""Остаток на складе для разбора строки — одинаково для товара и материала.

Был написан дважды, по разу на страницу: `product_detail._stock` и
`material_detail._stock` — один и тот же запрос и один и тот же словарь.
Два одинаковых куска расходятся молча, и разошлись — сначала в сериализаторах,
следом в компонентах фронтенда.

Фильтры страницы сюда не приходят намеренно: остаток это «сегодня», а не
«за апрель». Он отвечает на вопрос «хватит ли на следующую партию»,
который к выбранному периоду отношения не имеет.
"""

from core.models import Stock


def stock_of(product_id: int) -> dict | None:
    """Что лежит на складе сейчас. `None` — остатка в отчёте нет вовсе.

    Известен не по всем: на боевых данных остаток есть у 27 из 66 проданных
    товаров и у 125 из 161 материала. `None`, а не нули: ноль читается как
    «кончился», а это другое утверждение об учёте.
    """
    row = Stock.objects.filter(product_id=product_id).first()
    if row is None:
        return None
    return {
        "quantity": row.quantity,
        "reserved": row.reserved,
        "available": row.available,
        "stock_days": row.stock_days,
    }
