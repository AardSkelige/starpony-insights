"""Что считается документом, существующим в учёте.

Три условия — вид, не удалён, проведён — стояли одним выражением внутри
`api/supplies/services/selection.py`, пока приёмки читала одна страница.
Их понадобилось двум: «Материалы в приёмках» считает по позициям,
«Поставщики» — по самим документам, и предикат у них обязан быть один.

Разойдись он — две страницы за один период показали бы разные приёмки,
и разошлись бы молча: черновик приёмки выглядит обычным документом.

Живёт в `core/`, а не в `api/common/`: это утверждение о домене — «товар
пришёл и деньги потрачены», — а не о том, как страница разбирает адресную
строку. Период и поиск остаются в слое API, там им и место.
"""

from django.db.models import QuerySet

from core.models import Document, DocumentKind, DocumentPosition


def alive(kind: DocumentKind) -> QuerySet[Document]:
    """Документы одного вида, существующие в учёте.

    Удалённые исключены: исчезнувший из учёта документ не должен попадать
    ни в одну сумму. Непроведённые — тоже: по черновику приёмки товар
    на склад ещё не пришёл, а по черновику отгрузки его ещё не продали.
    """
    return Document.objects.filter(
        kind=kind, deleted_at__isnull=True, applicable=True
    )


def exists(document: Document | None) -> bool:
    """Существует ли документ в учёте: не удалён и проведён.

    Та же тройка условий, что у `alive`, но для одного объекта, а не запроса.
    Нужна там, где документ пришёл по ссылке: заказ у приёмки проверяется
    и расчётом срока, и выгрузкой, и разойдись они — файл покажет номер
    заказа рядом с прочерком в колонке срока.
    """
    return document is not None and document.deleted_at is None and document.applicable


def positions_in(documents: QuerySet[Document]) -> QuerySet[DocumentPosition]:
    """Строки перечисленных документов.

    Принимает запрос, а не список: выборка так и остаётся одним обращением
    к базе, вместо того чтобы сначала вытащить сотню документов ради их
    идентификаторов.
    """
    return DocumentPosition.objects.filter(document__in=documents)
