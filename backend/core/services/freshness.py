"""Свежесть данных: «данные на 14:32» в шапке каждой страницы.

Отдельным модулем, а не полем в каждом разделе: отметку показывают все десять
страниц, и вопрос «на какой момент эти числа» один и тот же для всех.

Берётся время последнего **успешного** прогона, а не последнего вообще.
Прогон, оборвавшийся на середине, оставляет данные наполовину вчерашними —
показать его время значило бы соврать ровно в том месте, которое существует,
чтобы не врать.
"""

from datetime import datetime

from core.models import SyncKind, SyncRun, SyncStatus


def last_success(kind: str) -> datetime | None:
    """Когда данные этого вида обновились в последний раз без потерь."""
    run = (
        SyncRun.objects.filter(kind=kind, status=SyncStatus.SUCCESS)
        .exclude(finished_at=None)
        .order_by("-finished_at")
        .first()
    )
    return run.finished_at if run else None


def documents_synced_at() -> datetime | None:
    """Отметка для разделов, считающих по документам: отгрузки, приёмки, маржа."""
    return last_success(SyncKind.DOCUMENTS)


def stock_synced_at() -> datetime | None:
    """Отметка для разделов, считающих по остаткам: что лежит на складе."""
    return last_success(SyncKind.STATE)


def oldest_of(*moments: datetime | None) -> datetime | None:
    """Самая старая из отметок. `None`, если хоть одна неизвестна.

    Нужна там, где страница считает по двум источникам сразу: «Расчёт
    производства» берёт продажи из документов, а остатки — из отчёта, и
    синхронизируются они по разным расписаниям, ночью и каждые 10–15 минут.

    Старшая, а не младшая: страница свежа настолько, насколько свеж её самый
    отставший источник. Показать младшую значило бы обещать актуальность,
    которой у половины чисел нет, — а именно этого отметка и должна не делать.

    `None` при любой неизвестной по той же причине: «данные на 12:37» рядом
    с остатками, которые не синхронизировались ни разу, — обещание, ничем
    не обеспеченное. Пустой набор — тоже `None`: вызов без отметок сейчас
    недостижим, но функция общая и лежит в `core/`, а `min()` по пустому
    набору падает.
    """
    if not moments or any(moment is None for moment in moments):
        return None
    return min(moment for moment in moments if moment is not None)
