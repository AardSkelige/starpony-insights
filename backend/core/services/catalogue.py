"""Что считать товаром, а что сырьём. Одно определение на весь проект.

**Товар — это то, у чего есть артикул** (решение 02.09). Сырьё и упаковка
артикула не имеют, и в МойСкладе оба вида лежат одной сущностью: делить их
больше нечем. На том же признаке стоит демон минимума — он пишет только тем,
у кого артикул есть, чтобы не затереть ручной порог у сырья.

Переехало сюда, когда определение понадобилось второму разделу: «Расчёт
производства» спрашивает «что варить», главная — «что кончилось и во что
вложены деньги», и множество у них обязано быть одно. Разойдись оно,
две страницы за один день насчитали бы разное число кончившихся позиций,
и обе выглядели бы правдоподобно.

**Архивные исключены у обоих.** Убранный в архив товар больше не выпускают,
и предлагать сварить его партию — предлагать работу, отменённую человеком.
Услуги исключены тоже: доставку не производят и не закупают на склад.
"""

from django.db.models import QuerySet

from core.models import Product, ProductKind


def _live() -> QuerySet[Product]:
    return Product.objects.alive().filter(kind=ProductKind.PRODUCT, archived=False)


def stocked() -> QuerySet[Product]:
    """Всё, что лежит на складе: товары и сырьё вместе, без услуг и архива.

    Понадобилось «Инвентаризации»: пересчитывают склад целиком, и делить его
    на «товар» и «сырьё» там нечем — вопрос «что давно не считали» одинаков
    для банки отдушки и для бутылки шампуня. Своё условие рядом с `goods()`
    пропустило бы ровно то, что чаще всего и не пересчитывают: из 241
    непересчитанной позиции 110 — сырьё.
    """
    return _live()


def goods() -> QuerySet[Product]:
    """Готовая продукция: то, что производят и продают."""
    return _live().exclude(article="")


def materials() -> QuerySet[Product]:
    """Сырьё и упаковка: то, из чего производят."""
    return _live().filter(article="")


# Группы, которые к производству отношения не имеют. Визитки, перчатки, скотч
# и коробки для переезда лежат в номенклатуре рядом с сырьём и артикула тоже
# не имеют — по одному этому признаку их не отличить.
#
# Разделять обязательно: «Визитка StarPony, 12 140 ₽, не расходуется» —
# правда, которая ничего не значит. Визитки и не должны расходоваться
# по техкартам, а в списке замороженного сырья они читаются как ошибка
# закупки. Владелец споткнулся об это на первом же показе.
HOUSEHOLD_PREFIX = "Хоз. товары"


def production_materials() -> QuerySet[Product]:
    """Только то, что участвует в производстве: сырьё, тара, этикетки.

    Плюс полуфабрикаты — у них артикула нет, а расход и остаток есть,
    и на складе они деньги наравне с сырьём.
    """
    return materials().exclude(folder__startswith=HOUSEHOLD_PREFIX)
