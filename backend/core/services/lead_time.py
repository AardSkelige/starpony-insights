"""Срок поставки: сколько проходит от заказа до прихода товара.

**Вторая половина порога закупки** (`PRD.md` §5.9). Первая — `coverage.py`,
запас в днях; вместе они отвечают на «пора ли заказывать»: хватит на шесть
дней, а везут восемь — значит уже поздно.

Живёт в `core/`, а не у страницы: тем же числом пользуются «Поставщики»
(кого торопить) и «Расчёт производства» (успеет ли сырьё к партии).

**Считается медианой, а не средним.** На боевых данных среднее по всем парам
4,77 дня против медианы 1,00 — впятеро. Половина закупок оформляется одним
днём («пришёл и взял»), вторая идёт от двух до сорока дней, и среднее между
ними описывает несуществующую середину. Медиана отвечает на «сколько обычно»,
а спрашивают именно это.

**Ноль дней — ответ, а не пробел.** У одних поставщиков медиана 7,7 дня
(разброс 0–20,3), у других ровно 0: первые везут, у вторых забирают. «В тот
же день» — факт учёта, и подменять его прочерком значило бы соврать.
Прочерк остаётся тому, у кого пар нет вовсе.

**Дни календарные, а не астрономические.** Заказ в 23:00 и приёмка в 09:00
следующего утра — это «на следующий день», а не «десять часов»: человек
планирует закупку днями, и дробь здесь только мешала бы.

**И календарь местный, а не UTC.** `moment.date()` у значения из базы даёт
UTC-дату: заказ, оформленный в час ночи по Москве, числился бы предыдущим
днём, и «в тот же день» превращалось бы в срок. Перевод — `core/dates.py`.
"""

import statistics
from dataclasses import dataclass
from decimal import Decimal
from typing import Iterable

from core.dates import days_between
from core.models import Document
from core.services.documents import exists


@dataclass(frozen=True)
class LeadTime:
    """Срок поставки вместе с тем, из чего он получен.

    Составляющие идут рядом с ответом, а не остаются на сервере: страница
    обязана показать формулу по наведению, и собирать её она должна
    из полученного, а не пересчитывать сама.
    """

    # Медиана срока в днях. `None` — связать не удалось ни одной приёмки,
    # и сказать нечего. Ноль сюда не годится: он значит «в тот же день».
    days: Decimal | None
    # Сколько приёмок удалось связать с заказом — знаменатель медианы.
    pairs: int
    # Сколько приёмок выборки остались без заказа. Показывается словами:
    # «срок по 12 приёмкам из 14» честнее, чем молчаливая медиана по части.
    unlinked: int

    min_days: int | None
    max_days: int | None
    # Среднее — только в объяснении, рядом с медианой. Расхождение между ними
    # само по себе говорит, насколько поставщик непредсказуем.
    average_days: Decimal | None


NOTHING = LeadTime(
    days=None, pairs=0, unlinked=0, min_days=None, max_days=None, average_days=None
)


def of(supplies: Iterable[Document]) -> LeadTime:
    """Срок по набору приёмок. Ждёт документы с подтянутым `purchase_order`.

    Приёмки приходят уже отобранными: период и поставщика знает страница,
    а не этот расчёт. Так же устроен `coverage.of` — сервис считает,
    выборку задаёт раздел.
    """
    days: list[int] = []
    unlinked = 0

    for supply in supplies:
        order = supply.purchase_order
        # Заказ входит в расчёт по тем же трём условиям, что и сама приёмка
        # (`core.services.documents.alive`): существует и проведён.
        #
        # Удалённый — потому что документа в учёте уже нет, и дата, от которой
        # считать, перестала быть фактом. Непроведённый — потому что черновик
        # заказа ничего не заказывал: датой он обзаводится в момент создания,
        # а обязательством не становится. Фильтруй мы черновики у приёмок
        # и не фильтруй у заказов, срок считался бы от намерения, которого
        # не было. В аккаунте такой заказ уже есть — один из 96.
        if not exists(order):
            unlinked += 1
            continue
        days.append(days_between(order.moment, supply.moment))

    if not days:
        return LeadTime(
            days=None,
            pairs=0,
            unlinked=unlinked,
            min_days=None,
            max_days=None,
            average_days=None,
        )

    return LeadTime(
        # Медиана чётного числа значений — среднее двух средних, и половина
        # дня здесь настоящая: у четырёх поставок по 0, 0, 7 и 8 дней срок
        # действительно «то сразу, то через неделю».
        days=Decimal(str(statistics.median(days))),
        pairs=len(days),
        unlinked=unlinked,
        min_days=min(days),
        max_days=max(days),
        average_days=Decimal(str(round(statistics.mean(days), 1))),
    )
