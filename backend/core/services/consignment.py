"""Товар на реализации: отгружен, но ещё не продан.

**По договору комиссии отгрузка — не продажа.** Товар уходит комиссионеру
на склад, а продажей становится с приходом отчёта комиссионера: до этого
он может вернуться. МойСклад считает так же — поэтому «Прибыльность»,
которая зеркалит отчёт прибыльности, и «Товары в отгрузках», которые считают
по отгрузкам, расходятся на 281 126 ₽ (на 03.09). **Обе цифры верны**, но
без пометки первая читается как выручка, которой ещё нет.

Опасность не умозрительная: у «Точки продаж» — крупнейшего канала страницы —
**87 % выручки** это товар на реализации, а у Telegram 97 %. Вывод «этот
канал приносит больше всех» держится на складе комиссионера.

**Здесь предикат, а не готовый агрегат.** «Товары в отгрузках» группируют
запросом и считают в SQL, «Каналы продаж» — в Python по загруженным
документам. Отдай мы им общую функцию агрегации, одному из двух пришлось бы
менять способ группировки ради общего кода. Так же устроен
`api.common.selection.matching`: условие переносится, готовый фильтр — нет.
"""

from dataclasses import dataclass
from decimal import Decimal

from django.db.models import Q, QuerySet, Sum

from core.models import ContractType, Document, DocumentKind
from core.money import share
from core.services.documents import alive


def where(prefix: str = "") -> Q:
    """Условие «ушло по договору комиссии».

    `prefix` — путь до документа. Пустой там, где строка и есть документ
    («Каналы» фильтруют сами отгрузки), `document__` — где строка это
    позиция («Товары в отгрузках»).

    Договор, а не контрагент: один и тот же покупатель берёт и по купле-
    продаже, и по комиссии — на 03.09 у двух комиссионеров три договора.
    """
    return Q(**{f"{prefix}contract__contract_type": ContractType.COMMISSION})


def shipments() -> QuerySet[Document]:
    """Отгрузки, ушедшие на реализацию, — **единственный** их запрос.

    Отсюда берут и «Каналы продаж» (вычитание в сводке), и «Сроки оплаты»
    (то, что вычитается из долга). Два запроса одного множества разошлись бы
    молча: одна страница фильтровала по оплате, другая нет, и обе показывали
    бы «Отгружено на реализацию» с разными числами.
    """
    return alive(DocumentKind.DEMAND).filter(where())


def is_consignment(document: Document | None) -> bool:
    """То же для одного документа — там, где раздел считает в Python.

    **Только отгрузка.** Отчёт комиссионера идёт по тому же договору, но он
    и есть продажа: посчитай его реализацией — и товар, ушедший на склад
    комиссионера, лёг бы в сумму дважды, сначала отгрузкой, потом отчётом.
    Отбор по виду именно здесь, а не у каждого вызывающего: вызывающий
    со смешанным списком появится позже и о правиле не вспомнит.

    `None` и документ без договора считаются продажей: договора комиссии
    в учёте нет, значит и реализации нет. Обратное умолчание пометило бы
    реализацией всё, у чего договор не заполнен.
    """
    return bool(
        document
        and document.kind == DocumentKind.DEMAND
        and document.contract_id
        and document.contract.is_commission
    )


@dataclass(frozen=True)
class Share:
    """Сколько из показанного — реализация, а не продажа."""

    total_kopecks: int
    consignment_kopecks: int

    @property
    def fraction(self) -> Decimal | None:
        """Доля реализации. `None` — показывать нечего: выручки нет вовсе."""
        return share(self.consignment_kopecks, self.total_kopecks)

    @property
    def tone(self) -> str:
        """Цвет полосы: `warning` там, где число нельзя читать как выручку.

        **Порог — половина.** Не «много реализации», а «больше половины
        показанного ещё не продано»: это уже другой вывод о канале,
        а не оговорка к прежнему. У «Точки продаж» 87 %, у Telegram 97 % —
        оба перекрашиваются; у МАХ 31 % полоса остаётся обычной, и доля
        подписывается словами.

        **Цветом в одиночку статус не передаётся** (`DESIGN.md` §1): подпись
        доли стоит рядом всегда, а не только при перекраске. Цвет отвечает
        на «стоит ли пересматривать вывод», подпись — на «насколько».

        Порог здесь, а не в компоненте: раскраска и текст обязаны меняться
        вместе. И `default` при нуле: пометка без повода перестаёт
        замечаться, а с ней и настоящие.
        """
        if self.consignment_kopecks <= 0:
            return "default"
        return "warning" if self.consignment_kopecks * 2 >= self.total_kopecks else "default"


def share_of(total_kopecks: int, consignment_kopecks: int) -> Share:
    return Share(
        total_kopecks=total_kopecks, consignment_kopecks=consignment_kopecks
    )


@dataclass(frozen=True)
class Outstanding:
    """Что лежит на реализации сейчас — состояние, а не итог периода."""

    shipped_kopecks: int
    reported_kopecks: int

    @property
    def pending_kopecks(self) -> int:
        """Отгружено минус продано отчётами.

        Отрицательным не бывает в здоровых данных, но подрезается: отчёт
        может прийти за отгрузку, которой в зеркале ещё нет, и «минус
        сорок тысяч на реализации» — число, которое ничего не значит.
        """
        return max(0, self.shipped_kopecks - self.reported_kopecks)


def outstanding() -> Outstanding:
    """Полная картина реализации — **без периода**.

    Периода здесь нет намеренно, и это то же решение, что у долга
    на «Сроках оплаты»: отчёт комиссионера приходит позже отгрузки, часто
    в следующем месяце. Сузь мы обе величины периодом, «отгружено за август»
    сравнивалось бы с «продано в августе» — а это отчёты за июль, то есть
    два разных множества в одном вычитании (`DESIGN.md` §8).

    Поэтому в выборке показывается только доля реализации (`Share`), а вся
    картина — состоянием на сегодня, отдельным блоком.
    """
    shipped = shipments().aggregate(total=Sum("total_kopecks"))["total"] or 0
    reported = (
        alive(DocumentKind.COMMISSION_REPORT)
        .aggregate(total=Sum("total_kopecks"))["total"]
        or 0
    )
    return Outstanding(shipped_kopecks=shipped, reported_kopecks=reported)
