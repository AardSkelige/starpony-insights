"""Текст для человека: склонение существительного при числе.

Близнец `frontend/src/shared/lib/plural.ts`. Дублирование здесь неизбежно —
языки разные, — но правило одно, и оба файла проверяются своим тестом.

Нужно везде, где число выводится вместе со словом: в подвале таблицы,
в строке итога выгрузки, в сводке. Иначе интерфейс говорит
«1 наименований», и это первое, что замечают в готовой странице.
"""


def plural(count: int, one: str, few: str, many: str) -> str:
    """Форма слова при числе: «наименование», «наименования», «наименований»."""
    # Одиннадцать–четырнадцать — исключение: они кончаются на 1–4,
    # но склоняются как «много».
    if 11 <= count % 100 <= 14:
        return many

    remainder = count % 10
    if remainder == 1:
        return one
    if remainder in (2, 3, 4):
        return few
    return many


def with_plural(count: int, one: str, few: str, many: str) -> str:
    """Число вместе со словом: «161 материал»."""
    return f"{count} {plural(count, one, few, many)}"
