"""Деньги и доли: арифметика, общая для всех разделов.

Правило проекта — суммы живут целыми копейками, а рубли и проценты
появляются только на слое отображения. Эти две функции стояли по копии
в каждом разделе, и копии разошлись сигнатурами: одна не умела принимать
«цены нет», другая умела.
"""

from decimal import Decimal


def share(part: int | None, whole: int) -> Decimal | None:
    """Доля, долей единицы. `None` — делить не на что или нечего делить.

    Ноль вместо `None` не годится: он читается как «доля нулевая», а на деле
    величина неизвестна — например, материал ни разу не покупали.
    """
    if part is None or whole <= 0:
        return None
    return Decimal(part) / Decimal(whole)


def rubles(kopecks: int | Decimal | None) -> float | None:
    """Копейки в рубли для выгрузки в XLSX. `None` остаётся `None`.

    Возвращает `float` намеренно: Excel считает в числах с плавающей точкой,
    и точность `Decimal` ему всё равно не передать. Файл — для чтения и сводных
    таблиц, а сверка до копейки идёт по экрану и по самому учёту.
    """
    if kopecks is None:
        return None
    return float(Decimal(kopecks) / 100)
