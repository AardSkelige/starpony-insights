"""Прибыльность: что продано за день, за сколько и какой ценой досталось.

Зеркало отчёта `/report/profit/byproduct`, по одной строке на товар и день.

**Зачем зеркалить чужой отчёт, а не считать самим.** Себестоимость нужна
**на момент продажи**, а в зеркале её взять негде: `/report/stock/all` знает
цену только того, что лежит на складе сейчас, и у 35 проданных товаров из 59
её нет вовсе — треть выручки осталась бы без маржи. МойСклад же считает FIFO
по каждой продаже сам и отдаёт готовым, одним запросом на период.

**По дням, а не за период.** Проверено запросами к боевому аккаунту: июль
целиком и сумма тридцати одного дневного запроса совпадают до копейки —
и по количеству, и по выручке, и по себестоимости. Значит из дней собирается
любой период, и страница не ходит в МойСклад за каждым выбором в календаре
(`CLAUDE.md` §1).

**Выручка здесь — деньги за проданное, а не за отгруженное.** Товар, ушедший
по договору комиссии, МойСклад считает проданным только с приходом отчёта
комиссионера. На 02.09 разница — 281 126 ₽: отгружено на реализацию 729 штук,
продано 208. Число меньше того, что показывают «Товары в отгрузках»,
и это не расхождение, а другой вопрос — «сколько заработали», а не
«сколько увезли».
"""

from django.db import models

from core.models.base import BackupGroup, DomainModel
from core.models.catalog import Product


class ProfitDay(DomainModel):
    """Продажи одного товара за один день: сколько, почём и по какой цене взято.

    Восстанавливается синхронизацией, поэтому в ежедневный бэкап не идёт.
    """

    backup_group = BackupGroup.MIRROR

    date = models.DateField("День", db_index=True)
    product = models.ForeignKey(
        Product, on_delete=models.CASCADE, related_name="profit_days",
        verbose_name="Товар",
    )

    # Количество — три знака, как везде: отчёт отдаёт его типом Float.
    quantity = models.DecimalField("Продано", max_digits=18, decimal_places=3, default=0)

    # Суммы — целые копейки: отчёт отдаёт их уже в копейках, и делить
    # их не на что. Здесь это именно суммы документов, а не удельные
    # величины, — правило `CLAUDE.md` §3.
    revenue_kopecks = models.BigIntegerField("Выручка, копейки", default=0)
    cost_kopecks = models.BigIntegerField("Себестоимость, копейки", default=0)

    # Часть тех же чисел, пришедшаяся на маркетплейсы, — **подмножество**
    # строки, а не соседнее с ней значение. Отдельной строкой они дали бы
    # двойной счёт при сложении, и это ровно тот дефект, который на трёх
    # страницах ловили как «соседние числа о разных множествах».
    #
    # Приходит вторым запросом, с фильтром по группе контрагента: признак
    # площадки живёт на контрагенте, а не на канале продаж. Вывести его
    # из канала нельзя — «Точка продаж» смешанная: 5 документов площадки
    # против 30 обычных.
    #
    # Нужны отдельно потому, что маржа по ним **завышена на весь процент
    # площадки**: Озон и ПМТ удерживают комиссию при выплате, и в учёт она
    # не попадает вовсе. Молча смешать их с прямыми продажами значит выдать
    # завышенное число за факт.
    marketplace_quantity = models.DecimalField(
        "Продано через площадки", max_digits=18, decimal_places=3, default=0
    )
    marketplace_revenue_kopecks = models.BigIntegerField(
        "Выручка через площадки, копейки", default=0
    )
    marketplace_cost_kopecks = models.BigIntegerField(
        "Себестоимость через площадки, копейки", default=0
    )

    updated_at = models.DateTimeField("Обновлено", auto_now=True)

    class Meta:
        verbose_name = "Прибыльность за день"
        verbose_name_plural = "Прибыльность по дням"
        constraints = [
            models.UniqueConstraint(
                fields=["date", "product"], name="profit_day_unique_product_per_day"
            )
        ]
        indexes = [models.Index(fields=["product", "-date"])]

    def __str__(self) -> str:
        return f"{self.product} — {self.date}"

    @property
    def profit_kopecks(self) -> int:
        """Прибыль до комиссии площадок и накладных расходов."""
        return self.revenue_kopecks - self.cost_kopecks
