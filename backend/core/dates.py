"""Календарный день из момента. Арифметика без домена — как `money.py`.

**`moment.date()` — это UTC-дата, а не день человека.** Django хранит время
в UTC и возвращает его же; `.date()` у такого значения отрезает московские
часы после полуночи в предыдущие сутки. Приёмка, проведённая 10 марта
в 01:00 по Москве, у себя в `.date()` числится девятым.

Цена ошибки — ровно один день, и она тихая:

| Где | Во что превращается |
|---|---|
| `lead_time` | «в тот же день» становится сроком в один день, и медиана поставщика съезжает |
| `regularity` | три приёмки одним днём считаются двумя днями поставок — ровно то, ради чего дедупликация и вводилась |
| `timeline` | границы ряда считаны по UTC, а корзины `Trunc*` — по московской, и крайние столбики выпадают |
| `coverage` | длина периода ±1 день, то есть тихое искажение дневного расхода |

Правило то же, что в `api/common/selection.py`: **день — понятие календаря,
а не UTC.** Там оно про границы периода, здесь — про сам момент.

В базе сейчас нет ни одного документа между полуночью и тремя ночи
по Москве, поэтому дефект не проявлялся. Это не причина его оставить:
ночная приёмка появится, и ошибка не подаст ни одного признака.
"""

from datetime import date, datetime

from django.utils import timezone


def local_date(moment: datetime) -> date:
    """День, в который это произошло по местному календарю.

    Тот же часовой пояс, в котором считает Postgres (`TIME_ZONE`), — иначе
    даты, посчитанные в Python, не сойдутся с датами, посчитанными запросом.
    """
    return timezone.localtime(moment).date()


def days_between(earlier: datetime, later: datetime) -> int:
    """Сколько календарных дней прошло. Один день, а не двадцать четыре часа.

    Заказ в 23:00 и приёмка в 09:00 следующего утра — «на следующий день»,
    а не «десять часов»: закупку планируют днями.
    """
    return (local_date(later) - local_date(earlier)).days
