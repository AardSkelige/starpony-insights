"""Выборка страницы: период, поиск, разбиение на страницы.

Общее основание разделов. «Товары в отгрузках» и «Материалы в отгрузках»
отбирают позиции отгрузок, «Материалы в приёмках» — позиции приёмок, но
период, поиск и страница у всех устроены одинаково, и разойдись они,
две страницы за один период показали бы разное.

Что именно отбирается — знает раздел: у отгрузок есть канал продаж,
у приёмок его нет вовсе, зато есть поставщик. Поэтому здесь только то,
что от вида документа не зависит.

Границы периода живут здесь же: день — понятие календаря, а не UTC, и
сравнение с концом дня теряет документ, проведённый в 23:59:59.5.
"""

from dataclasses import dataclass
from datetime import date, datetime, time, timedelta

from django.db.models import Q
from django.utils import timezone

# Потолок высоты страницы. Общий: он защищает базу от ссылки с `size=100000`,
# а база у страниц одна.
MAX_PAGE_SIZE = 200
# Столько же, сколько по умолчанию показывает таблица на экране
# (`PAGE_SIZES` во фронтенде). Два разных умолчания значили бы, что ответ
# из `/api/docs` не совпадает с тем, что человек видит на странице.
DEFAULT_PAGE_SIZE = 10


@dataclass(frozen=True)
class Filters:
    """Что человек выбрал в панели фильтров — общая часть для всех страниц.

    Период, поиск и разбиение на страницы устроены одинаково у всех: они
    приходят из адресной строки и оттуда же восстанавливаются по ссылке.
    Своё у страницы — какой справочник фильтрует выборку (канал у отгрузок,
    поставщик у приёмок) и какие сортировки она понимает; и то, и другое
    задаётся наследником, ровно как у сериализаторов запроса.

    `ordering` здесь нет намеренно: у него нет умолчания, верного для всех
    страниц. У «Товаров» это `-revenue`, у «Материалов» такого ключа нет
    вовсе — общее умолчание пришлось бы придумывать, и оно было бы неверным.
    """

    date_from: date | None = None
    date_to: date | None = None
    search: str = ""
    page: int = 1
    page_size: int = DEFAULT_PAGE_SIZE


def page_bounds(page: int, page_size: int) -> tuple[int, int]:
    """Границы среза страницы: откуда и докуда резать.

    Годится и для запроса, и для готового списка — «Товары» режут QuerySet,
    «Материалы» список после разворота техкарт, а арифметика у них одна.

    Высота подрезается и здесь тоже. Запрос снаружи до этого места
    с несуразной высотой не доходит — сериализатор отвечает четырёхсотой, —
    но `page()` зовут ещё из тестов и из выгрузки, а защита базы от
    `size=100000` не должна зависеть от того, кто позвал.
    """
    size = max(1, min(page_size, MAX_PAGE_SIZE))
    start = max(0, (page - 1) * size)
    return start, start + size


def day_start(day: date) -> datetime:
    """Начало дня в текущем поясе: граница периода — про календарь, не про UTC."""
    return timezone.make_aware(datetime.combine(day, time.min))


def day_after(day: date) -> datetime:
    """Начало следующего дня: верхняя граница строгая, чтобы день вошёл целиком.

    Сравнивать с концом дня нельзя: `moment` хранит секунды, и документ,
    проведённый в 23:59:59.5, выпал бы из периода без единого признака.
    """
    return day_start(day) + timedelta(days=1)


def within(
    queryset,
    date_from: date | None,
    date_to: date | None,
    *,
    field: str = "document__moment",
):
    """Сузить выборку периодом. Пустая граница — не ограничивает.

    `field` — путь до даты документа. По умолчанию это строка документа
    (`document__moment`), потому что так считают три страницы из четырёх.
    «Поставщики» считают по самим приёмкам, и там путь — просто `moment`.

    Параметром, а не второй функцией: правило про границы дня здесь одно,
    и вторая копия разошлась бы ровно на том документе, что проведён
    в 23:59:59.5.
    """
    if date_from:
        queryset = queryset.filter(**{f"{field}__gte": day_start(date_from)})
    if date_to:
        queryset = queryset.filter(**{f"{field}__lt": day_after(date_to)})
    return queryset


def matching(term: str, *, prefix: str = "product__") -> Q:
    """Условие поиска по номенклатуре: название, артикул, код.

    Возвращает условие, а не отфильтрованный запрос: у «Материалов» искать
    надо по полю `product`, а у деталей строки — по другому пути к тому же
    товару. Условие переносится, готовый фильтр — нет.

    `prefix` — путь до товара. По умолчанию строка таблицы это позиция
    документа, и до товара идут через `product__`; у «Расчёта производства»
    строка и есть товар, и путь пустой.

    Параметром, а не второй функцией, — по тому же доводу, что у `within`:
    поля поиска здесь перечислены один раз, и вторая копия разошлась бы
    на первом же добавленном поле. Тогда «нашлось у соседей, не нашлось
    здесь» списали бы на данные, а не на разъехавшийся список полей.

    **Пробелы срезаются здесь же.** Раньше это делал каждый раздел сам,
    и «Расчёт производства» забыл: запрос, вставленный из буфера с ведущим
    пробелом, не находил ничего, хотя на соседних страницах находил.
    Одна забывчивость на раздел — значит правило живёт в одном месте.
    """
    term = term.strip()
    return (
        Q(**{f"{prefix}name__icontains": term})
        | Q(**{f"{prefix}article__icontains": term})
        | Q(**{f"{prefix}code__icontains": term})
    )
