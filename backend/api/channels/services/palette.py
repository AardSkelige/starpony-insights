"""За каким каналом закреплён цвет графика.

**Цвет следует за каналом, а не за его местом в списке.** Возьми мы номер
слота из текущей сортировки — смена периода перекрашивала бы каналы: тот же
Озон был бы синим в августе и зелёным за квартал, и два графика на одном
экране рассказывали бы про разные вещи одним цветом.

Поэтому слот закрепляется по выручке **за всю историю**, а не за выбранный
период: это тоже ранжирование, но оно меняется медленно и не зависит
от того, что человек сейчас отфильтровал.

**Слотов восемь, каналов девять.** Восьмёрка — не круглое число, а предел
палитры (`frontend/src/index.css`): дальше оттенки перестают надёжно
различаться, в том числе при дальтонизме. Девятый канал получает `None`
и рисуется приглушённым «Другим» — повторить цвет значило бы сказать
«это тот же канал».
"""

from django.db.models import Sum

from core.models import DocumentKind
from core.services.documents import alive

# Столько категориальных слотов в палитре темы.
SLOTS = 8


def slots() -> dict[int, int]:
    """Канал → номер слота (1…8). Каналов сверх восьми в словаре нет.

    Считается по всей истории отгрузок и одним запросом: девять строк
    группировки, и кэшировать тут нечего.
    """
    rows = (
        alive(DocumentKind.DEMAND)
        .exclude(sales_channel=None)
        .values("sales_channel_id")
        .annotate(revenue=Sum("total_kopecks"))
        # Идентификатор в ключе разрешает ничью: два канала с равной выручкой
        # иначе менялись бы слотами между запросами, и цвет прыгал бы
        # без единой причины на экране.
        .order_by("-revenue", "sales_channel_id")
    )
    return {
        row["sales_channel_id"]: index
        for index, row in enumerate(rows[:SLOTS], start=1)
    }
