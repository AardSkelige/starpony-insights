"""Линейки товаров: как свернуть сорок наименований в пять строк.

**Спрашивают «что покупают», а отвечать наименованиями нечем.** У канала
их сорок пять, и первые пять — это «Кондиционер для гривы и хвоста
Табак-Ваниль 500 мл», «…Кокосовое молоко 500 мл», «…Персик-Банан 500 мл»:
три строки об одном товаре в трёх запахах. Список отвечает на вопрос,
которого не задавали, — «какой вкус берут», — и молчит о том, который
задали: кондиционеры это или репелленты.

**Строка — это линейка в одном объёме.** Не просто линейка: пол-литровый
кондиционер и пятилитровый продаются разным людям и разными деньгами,
и сложить их в «Кондиционер» значит потерять ровно то различие, ради
которого в список смотрят. Поэтому «Кондиционер 500 мл» и «Кондиционер
5000 мл» — две строки.

**Линейку задаёт артикул, а не догадка по названию.** В учёте StarPony
артикул устроен как `200.036.05`: первый сегмент — линейка (100 шампуни,
200 кондиционеры, 300 репелленты, 400 уход за амуницией), дальше вкус
и объём. Это классификация, которую ведёт владелец, а не выведенная нами
из текста. Объём читается из названия — «500 мл» стоит в конце у всех.

**Подпись — из самих названий, а не сочинённое слово.** Назвать группу
«Кондиционеры» значит придумать термин, которого в учёте нет; «Кондиционер
500 мл» — это первое слово названия и объём из него же, оба факта.
Полное название никуда не девается: оно уходит в подсказку вместе с составом
линейки. Если общего начала нет (в линейке `400` это воск, масло, пенка
и кондиционер для амуниции), группа не собирается вовсе: товары идут
отдельными строками — но подпись всё равно короткая, «Масло 250 г».

**Совпавшие подписи разводятся полным именем.** «Кондиционер 250 мл» может
оказаться и кондиционером для гривы, и кондиционером для амуниции: первое
слово общее, объём тот же, товары разные. Две одинаковые строки читаются
как ошибка расчёта, поэтому обе получают полное название.

Товар без артикула — всегда своя строка: доставка, короб и пробник линейки
не образуют.
"""

import re

# Сколько слов должно совпасть, чтобы общее начало считалось именем линейки.
#
# Три, а не два. Двух хватает «Кондиционеру для», под которым уживаются
# кондиционер для гривы и хвоста и кондиционер для амуниции: разные товары,
# разные линейки, и общая подпись соврала бы про обе. На боевых названиях
# порог проходят все настоящие линейки — «Шампунь для лошадей» (три слова),
# «Кондиционер для гривы и хвоста» (пять), «Репеллент для лошадей Против
# насекомых» (пять).
MIN_WORDS = 3

# Сколько вариантов назвать в подсказке. Остальные — «и ещё N»: подсказка
# отвечает на «что там внутри», а не заменяет список наименований.
VARIANTS = 5

# Объём в конце названия: «500 мл», «150 г», «5 кг». Единицы перечислены,
# а не взяты как «любое слово»: без этого «Кондиционер для гривы и хвоста
# Кока-Кола» отдал бы «Кока-Кола» за объём.
_VOLUME = re.compile(r"\b(\d+(?:[.,]\d+)?)\s*(мл|л|г|кг|шт)\b\s*$", re.IGNORECASE)


def line_of(product) -> str:
    """Ключ линейки: первый сегмент артикула. Без артикула — сам товар."""
    head = (product.article or "").split(".")[0].strip()
    return head if head else f"#{product.id}"


def volume_of(name: str) -> str:
    """Объём из конца названия: «500 мл». Пусто — объёма в названии нет."""
    found = _VOLUME.search(name.strip())
    return f"{found.group(1)} {found.group(2).lower()}" if found else ""


def common_prefix(names: list[str]) -> str:
    """Общее начало названий, по целым словам.

    По словам, а не по буквам: посимвольное совпадение обрывается посреди
    слова — «Кондиционер для гривы и хвоста Кока-Кола» и «…Кокосовое молоко»
    дали бы «…Ко», и подпись группы превратилась бы в обрубок.
    """
    if not names:
        return ""

    words = [name.split() for name in names]
    prefix: list[str] = []
    for index in range(min(len(item) for item in words)):
        word = words[0][index]
        if any(item[index] != word for item in words):
            break
        prefix.append(word)
    return " ".join(prefix)


def variant_of(name: str, prefix: str) -> str:
    """Чем этот товар отличается от соседей по линейке: «Табак-Ваниль».

    Из названия вычитается общее начало и объём — остаётся ровно то, что
    у товаров разное. Не осталось ничего — возвращается само название:
    пустая строка в подсказке была бы хуже длинной.
    """
    tail = name.strip()
    if prefix and tail.startswith(prefix):
        tail = tail[len(prefix) :].strip()
    volume = volume_of(tail)
    if volume:
        tail = _VOLUME.sub("", tail).strip()
    return tail or name.strip()


def grouped(entries: dict[int, dict]) -> list[dict]:
    """Свернуть наименования в линейки одного объёма.

    На входе — товары канала: идентификатор в ключ, выручка и название
    в значение. На выходе — строки списка: линейка в одном объёме либо
    отдельный товар, если сворачивать нечего.

    Сумма на выходе равна сумме на входе. Это не вежливость, а условие:
    слагаемые списка складываются в выручку канала, и потеряйся здесь
    товар — разница выглядела бы потерянными деньгами.
    """
    groups: dict[tuple[str, str], list[dict]] = {}
    for entry in entries.values():
        key = (entry["line"], volume_of(entry["name"]))
        groups.setdefault(key, []).append(entry)

    rows: list[dict] = []
    for (_, volume), items in groups.items():
        prefix = common_prefix([item["name"] for item in items])
        if len(items) < 2 or len(prefix.split()) < MIN_WORDS:
            rows.extend(
                {
                    # Короткая подпись и у одиночного товара: список, где
                    # «Кондиционер 500 мл» соседствует с «Репеллент для
                    # лошадей Против насекомых 500 мл», читается как два
                    # разных списка. Полное имя — в подсказке.
                    "name": _with_volume(
                        item["name"].split()[0], volume_of(item["name"])
                    ),
                    "full_name": item["name"],
                    "revenue_kopecks": item["revenue_kopecks"],
                    "items_count": 1,
                    "variants": [],
                }
                for item in items
            )
            continue

        # Короткая подпись — первое слово общего начала плюс объём:
        # «Кондиционер 500 мл». Полная остаётся про запас, на случай
        # двух групп с одинаковой короткой подписью.
        short = prefix.split()[0]
        variants = [
            variant_of(item["name"], prefix)
            for item in sorted(
                items, key=lambda item: -item["revenue_kopecks"]
            )
        ]
        rows.append(
            {
                "name": _with_volume(short, volume),
                "full_name": _with_volume(prefix, volume),
                "revenue_kopecks": sum(item["revenue_kopecks"] for item in items),
                "items_count": len(items),
                "variants": variants,
            }
        )

    return _unambiguous(rows)


def _with_volume(name: str, volume: str) -> str:
    return f"{name} {volume}".strip()


def _unambiguous(rows: list[dict]) -> list[dict]:
    """Развести строки, у которых короткая подпись совпала.

    «Кондиционер 250 мл» может оказаться и кондиционером для гривы,
    и кондиционером для амуниции: первое слово у них общее, объём тоже,
    а товары разные. Две одинаковые строки в списке читаются как ошибка
    расчёта, поэтому обе получают полное общее начало.
    """
    seen: dict[str, int] = {}
    for row in rows:
        seen[row["name"]] = seen.get(row["name"], 0) + 1

    return [
        {**row, "name": row["full_name"] if seen[row["name"]] > 1 else row["name"]}
        for row in rows
    ]
