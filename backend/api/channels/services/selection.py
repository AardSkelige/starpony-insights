"""Выборка раздела «Каналы продаж»: отгрузки периода, а не их строки.

Единица счёта — документ. Отгрузка это одна продажа, и все числа страницы
считаются по ней: выручка — сумма документа, чек — она же, покупатель —
контрагент документа. Позиции нужны отдельно и только ради ассортимента:
сколько наименований уходит через канал и какие именно.

**Сумма берётся из документа, а не складывается из позиций** — то же
правило, что у «Поставщиков». Сумма документа остаётся фактом учёта, даже
если синхронизация пропустит позицию; сложение позиций в этот момент
разойдётся с учётом и промолчит.

**Справочника для сужения здесь нет.** У «Товаров в отгрузках» фильтр
по каналу сужает выборку, потому что строка там — товар. Здесь канал и есть
строка: выбери его — в таблице останется одна, а сравнивать станет не с чем.
Сужают период и поиск по названию канала.
"""

from dataclasses import dataclass
from datetime import date

from django.db.models import QuerySet

from api.common import selection
from core.models import Document, DocumentKind
from core.services.documents import alive


@dataclass(frozen=True)
class Filters(selection.Filters):
    """Фильтры страницы. Своё у неё — только порядок строк.

    Поиск сужает каналы по названию, период — отгрузки. Разные вещи: период
    меняет то, что посчитано, а поиск — только то, что показано.
    """

    ordering: str = "-revenue"


def demands(
    *, date_from: date | None = None, date_to: date | None = None
) -> QuerySet[Document]:
    """Отгрузки периода вместе с каналом и покупателем.

    Связи подтягиваются здесь: без канала и контрагента каждая строка
    таблицы стоила бы запроса на документ. На трёхстах отгрузках это
    незаметно и станет заметно ровно тогда, когда история дорастёт
    до десятков тысяч.

    Отгрузки **без канала** отсюда не выброшены намеренно. Их одна из 306,
    и в таблицу они не попадут — канала у них нет, — но в сводке обязаны
    быть посчитаны: иначе итог страницы разойдётся с учётом на эту одну,
    и объяснить расхождение будет нечем.
    """
    queryset = alive(DocumentKind.DEMAND).select_related(
        "sales_channel", "agent",
        # Договор — ради различия «продано» и «отгружено на реализацию».
        # Без него `is_consignment` делал бы запрос на каждую из 328
        # отгрузок: не падение, а тихая трата, видимая только в счётчике.
        "contract",
    )
    return selection.within(queryset, date_from, date_to, field="moment")
