"""Выборка «Расчёта производства»: период продаж, горизонт и состав партии.

Своё у раздела ровно две вещи — **горизонт** и **партия**; период и поиск
общие и берутся из `api/common/selection.py`.

**Разбиения на страницы здесь нет намеренно.** У остальных разделов оно
защищает базу от выборки в тысячи строк; здесь множество закрыто и мало —
57 товаров с артикулом и несколько десятков материалов под партию. А главное,
страница отвечает одной цепочкой «что кончается → сколько произвести → что
закупить», и разрезать её на страницы значит порвать ровно то, ради чего
её открывают: человек не может сравнить дефицит на второй странице
с партией на первой.

**Партия едет в адресной строке, а не в теле запроса.** Так же, как период
у соседних разделов: ссылку можно переслать, кнопка «назад» возвращает
предыдущий расчёт, а перезагрузка страницы не стирает подобранное. Ключ —
артикул, а не наш внутренний номер: артикул и есть личность товара
(решение 02.09), он переживает пересоздание зеркала, и по нему же товар
ищут глазами.
"""

import re
from dataclasses import dataclass

from rest_framework import serializers

from api.common.selection import Filters as CommonFilters

# На сколько дней вперёд производим. Он же — страховой запас из `PRD.md` §5.9,
# который там записан открытым вопросом: вместо того чтобы придумать число
# в коде, страница даёт его выбрать и показывает последствия на живых числах.
# Шестьдесят по умолчанию: месяц — типичный интервал между варками, и запаса
# на два месяца хватает, чтобы не варить в спешке.
DEFAULT_HORIZON = 60
MIN_HORIZON = 1
MAX_HORIZON = 365

# Потолок числа позиций в партии. Товаров с артикулом всего 57, и запросить
# больше нечего; ограничение защищает не от человека, а от ссылки, собранной
# руками, которая иначе развернула бы техкарты сотни тысяч раз.
MAX_BATCH_LINES = 200

# Сколько штук можно заказать одной строкой. Семь знаков — с большим запасом
# к годовому выпуску (самый ходовой товар уходит по 382 штуки за квартал),
# и при этом разворачивание техкарт остаётся в разумных числах.
MAX_LINE_QUANTITY = 9_999_999

# Артикул с количеством или без: `200.040.05:200` и `200.040.05`.
#
# **Без количества значит «посчитай сам»** — столько, чтобы хватило
# на выбранный горизонт. Так в партию попадает то, что отметили галочкой
# или кнопкой «Взять всё»: этих чисел человек не вводил, их предлагает
# расчёт, и они обязаны меняться вместе с горизонтом.
#
# Артикулы в учёте имеют вид `999.999.99`, двоеточия в них не бывает — но
# выражение допускает любой знак, кроме двоеточия, чтобы смена схемы
# артикулов не потребовала правки разбора адресной строки.
_ITEM = re.compile(r"^(?P<article>[^:]{1,100})(?::(?P<quantity>\d{1,7}))?$")


@dataclass(frozen=True)
class Filters(CommonFilters):
    """Что человек выбрал. Горизонт и партия — сверх общей части.

    `page` и `page_size` наследуются, но не используются: см. про отсутствие
    разбиения на страницы в шапке модуля. Оставлены в родителе, а не
    переопределены пустыми, потому что подменять поля базового класса ради
    того, чтобы их не звать, — способ получить два разных `Filters`.
    """

    horizon: int = DEFAULT_HORIZON


def parse_batch(values: list[str]) -> dict[str, int | None]:
    """Разобрать `item=артикул:количество` из адресной строки.

    Отвергает запрос целиком, а не пропускает непонятное: строка,
    составленная не по форме, — это сломанная ссылка, а не выбор человека,
    и молча выкинуть её значит показать расчёт по половине партии, ничем
    не отличающийся с виду от расчёта по целой.

    Товар, которого нет в учёте, — другое дело: ссылка могла быть верной
    вчера. Он проверяется дальше, при расчёте, и возвращается человеку
    названным. Здесь — только форма.
    """
    if len(values) > MAX_BATCH_LINES:
        raise serializers.ValidationError(
            {"item": f"Слишком много позиций в партии: {len(values)}, "
                     f"допустимо не больше {MAX_BATCH_LINES}."}
        )

    batch: dict[str, int | None] = {}
    for value in values:
        match = _ITEM.match(value.strip())
        if match is None:
            raise serializers.ValidationError(
                {"item": f"Строка «{value}» не похожа на «артикул:количество»."}
            )

        # Пустым он быть не может: `value.strip()` выше срезает пробелы,
        # и выражение требует хотя бы один знак до двоеточия — `item=%20:5`
        # не проходит формой, а не проверкой на пустоту. Своей проверки
        # здесь нет намеренно: она была бы недостижимой, а недостижимый
        # охранник хуже отсутствующего — ему верят.
        article = match["article"].strip()

        if match["quantity"] is None:
            # «Посчитай сам». Смешивать с числом нельзя: если тот же артикул
            # пришёл и с количеством, побеждает количество — человек его
            # ввёл руками, и затирать введённое расчётом мы не вправе.
            batch.setdefault(article, None)
            continue

        # Штуки, а не дробь: все 57 товаров с артикулом измеряются в штуках,
        # и половины флакона не бывает. Дробное количество сюда просто
        # не проходит разбором — `\d+` его не примет.
        quantity = int(match["quantity"])
        if quantity <= 0:
            raise serializers.ValidationError(
                {"item": f"Количество в строке «{value}» должно быть больше нуля."}
            )
        batch[article] = (batch.get(article) or 0) + quantity

    # Потолок проверяется **после** сложения повторов. До него
    # `item=A:9999999&item=A:9999999` давало двадцать миллионов в одной
    # позиции — вдвое выше объявленного предела, и объявленного зря.
    for article, quantity in batch.items():
        if quantity is not None and quantity > MAX_LINE_QUANTITY:
            raise serializers.ValidationError(
                {"item": f"Количество по артикулу «{article}» больше допустимого."}
            )

    return batch
