"""Окно главной: последний полный месяц и предыдущий.

**Идущий месяц в сравнения не входит.** Четвёртого сентября он содержит
четыре дня из тридцати, и «сентябрь против августа» показал бы падение
на девяносто процентов там, где ничего не случилось. Поэтому итоги
подводятся по последнему **полному** месяцу, а идущий живёт отдельно —
на графике бледным столбиком, вне сравнений.

**Окно называется на экране, а не подразумевается.** Число без месяца
не привязано ни к чему: «640 475 ₽» одинаково выглядит и как выручка
августа, и как выручка недели. Поэтому каждая карточка отдаёт своё окно
вместе с числами, а не полагается на общую подпись в шапке, — окна
у карточек **разные**, и одна подпись на всех соврала бы.
"""

from dataclasses import dataclass
from datetime import date, timedelta

from core.dates import today as local_today

# Два падежа, а не один. Именительный стоит там, где месяц — подлежащее
# («Август 2026 к июлю 2026»), родительный — там, где он дополнение
# («Итоги августа 2026»). Одной формой не обойтись: «Итоги август» и
# «Августа 2026 против июля» одинаково нечитаемы, и владелец споткнулся
# об оба.
#
# Склонение живёт на сервере, а не на фронте: месяц приходит вместе
# с числами, которые он описывает, и разъехаться им негде. Тот же довод,
# что у `core/text.py`.
MONTH_NAMES = (
    "январь", "февраль", "март", "апрель", "май", "июнь",
    "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь",
)
MONTH_NAMES_OF = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)
# Дательный: «к июлю 2026». Нужен ровно одному сравнению, но собирать его
# на фронте значило бы завести там третью таблицу месяцев.
MONTH_NAMES_TO = (
    "январю", "февралю", "марту", "апрелю", "маю", "июню",
    "июлю", "августу", "сентябрю", "октябрю", "ноябрю", "декабрю",
)


@dataclass(frozen=True)
class Month:
    """Месяц целиком: обе границы включительно."""

    first: date
    last: date

    @property
    def label(self) -> str:
        """«Август 2026» — именительный, когда месяц подлежащее."""
        name = MONTH_NAMES[self.first.month - 1]
        return f"{name.capitalize()} {self.first.year}"

    @property
    def label_of(self) -> str:
        """«августа 2026» — родительный, для подписи «Итоги …»."""
        return f"{MONTH_NAMES_OF[self.first.month - 1]} {self.first.year}"

    @property
    def label_to(self) -> str:
        """«июлю 2026» — дательный, для сравнения «Август к июлю»."""
        return f"{MONTH_NAMES_TO[self.first.month - 1]} {self.first.year}"

    @property
    def days(self) -> int:
        return (self.last - self.first).days + 1


def month_of(day: date) -> Month:
    """Месяц, которому принадлежит день.

    Последний день считается через первое число следующего месяца:
    арифметика по числу дней ошибается на феврале и на декабре.
    """
    first = day.replace(day=1)
    next_first = (first + timedelta(days=32)).replace(day=1)
    return Month(first=first, last=next_first - timedelta(days=1))


def previous(month: Month) -> Month:
    """Предыдущий месяц — тот, с которым сравнивают."""
    return month_of(month.first - timedelta(days=1))


@dataclass(frozen=True)
class Window:
    """Окно страницы: с чем сравниваем и что показываем отдельно."""

    # Последний полный месяц — по нему подводятся итоги.
    current: Month
    # Предыдущий полный — с ним сравнивают.
    earlier: Month
    # Идущий месяц. `None` первого числа: он ещё пуст, и показывать
    # «0 из 30» значило бы объявить провал в день, когда он не начался.
    running: Month | None
    # Сколько дней идущего месяца уже прошло — для честной оговорки
    # «4 дня из 30» рядом с бледным столбиком.
    running_days: int


def window(today: date | None = None) -> Window:
    """Окно на сегодня.

    Первого числа последний полный месяц — вчерашний, и идущего нет вовсе:
    один день из тридцати не столбик, а точка, и подпись «идёт 1 день»
    сообщает ровно ничего.
    """
    day = today or local_today()
    running_month = month_of(day)
    passed = (day - running_month.first).days + 1

    current = previous(running_month)
    return Window(
        current=current,
        earlier=previous(current),
        running=running_month if passed > 1 else None,
        running_days=passed,
    )
