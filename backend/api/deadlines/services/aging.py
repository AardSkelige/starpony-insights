"""Старение долга: как давно деньги не приходят.

**Возраст заменяет срок ровно там, где срока нет.** Дата оплаты в учёте
не хранится, а считается — «дата документа плюс дни отсрочки», — и отсрочка
не проставлена ни у одного из 107 контрагентов. Значит сказать «просрочено»
сегодня не о чем. А вот «отгружено 93 дня назад и не оплачено» — факт учёта,
который есть всегда и не ждёт, пока владелец заполнит поля.

**Границы взяты от жизни, а не от бухгалтерского шаблона.** Тридцать дней —
это обещанный цикл выплаты площадки: в комментарии к платежу Яндекса рукой
написано «еженедельная с отсрочкой на 4 недели». Всё, что старше, уже
разошлось с обещанием, кто бы его ни давал. Классическая шкала 0–7 / 8–30 /
31–60 / 61–90 / 90+ на нынешних данных даёт две последние корзины из четырёх
и двух документов — две ниточки в графике вместо ответа.

**Корзины упорядочены, а не равноправны.** Поэтому на экране им положен
последовательный оттенок, светлый к тёмному, а не категориальные цвета:
цвет здесь кодирует то же, что и порядок, — «насколько всё плохо».
"""

from dataclasses import dataclass
from enum import StrEnum

from core.money import share


class AgeBucket(StrEnum):
    """Полки возраста. Порядок — от свежего к застарелому."""

    FRESH = "fresh"
    RECENT = "recent"
    STALE = "stale"
    OLD = "old"


@dataclass(frozen=True)
class Shelf:
    """Полка вместе с её верхней границей. `None` — последняя, без потолка."""

    bucket: AgeBucket
    up_to_days: int | None
    label: str


# Обещанный цикл выплаты: столько ждать нормально, дальше — повод спросить.
# Число живёт здесь одно на всё: заголовок блока на экране говорит «старше
# 30 дней», и разъедься он с полками, фраза осталась бы прежней, а складывать
# стала бы другие корзины — молча.
PROMISED_CYCLE_DAYS = 30

SHELVES: tuple[Shelf, ...] = (
    Shelf(AgeBucket.FRESH, 14, "до 14 дней"),
    Shelf(AgeBucket.RECENT, 30, "15–30 дней"),
    Shelf(AgeBucket.STALE, 60, "31–60 дней"),
    Shelf(AgeBucket.OLD, None, "больше 60 дней"),
)

BY_BUCKET = {shelf.bucket: shelf for shelf in SHELVES}


def bucket_of(age_days: int) -> AgeBucket:
    """На какой полке лежит долг такого возраста.

    Сравнение нестрогое сверху: долг возрастом ровно 30 дней — ещё «15–30»,
    а не «31–60». Иначе граница, названная на экране, означала бы не то,
    что написано.
    """
    for shelf in SHELVES:
        if shelf.up_to_days is None or age_days <= shelf.up_to_days:
            return shelf.bucket
    return AgeBucket.OLD


def is_fresh(shelf: Shelf) -> bool:
    """Уложился ли долг этой полки в обещанный цикл выплаты."""
    return shelf.up_to_days is not None and shelf.up_to_days <= PROMISED_CYCLE_DAYS


def distribution(debts: list) -> list[dict]:
    """Сколько денег и документов на каждой полке.

    Пустые полки остаются в списке: пропущенная корзина превращает шкалу
    возраста в произвольный набор столбиков, и «между 15 и 60 днями ничего
    нет» перестаёт читаться — это утверждение о данных, и оно должно быть
    видно.

    Доля считается от переданного набора, а не от всего долга: набор задаёт
    вызывающий, и смешать здесь два множества значило бы отдать наружу дробь,
    у которой числитель об одном, а знаменатель о другом.
    """
    totals = {shelf.bucket: {"count": 0, "debt_kopecks": 0} for shelf in SHELVES}
    for debt in debts:
        entry = totals[bucket_of(debt.age_days)]
        entry["count"] += 1
        entry["debt_kopecks"] += debt.debt_kopecks

    whole = sum(entry["debt_kopecks"] for entry in totals.values())
    return [
        {
            "key": shelf.bucket,
            "label": shelf.label,
            # Потолок полки — чтобы подпись на экране собиралась из данных,
            # а не повторяла число, записанное здесь.
            "up_to_days": shelf.up_to_days,
            # Уложился ли долг в обещанный цикл выплаты. Признак считается
            # тут, рядом с границами: два места, знающие про 30 дней,
            # однажды разойдутся, и разойдутся тихо.
            "fresh": is_fresh(shelf),
            "count": totals[shelf.bucket]["count"],
            "debt_kopecks": totals[shelf.bucket]["debt_kopecks"],
            "share": share(totals[shelf.bucket]["debt_kopecks"], whole),
        }
        for shelf in SHELVES
    ]
