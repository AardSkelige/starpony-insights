"""Норма расхода и распределение по изделиям — то, ради чего строку раскрывают.

Заменяет собой список «изделие → путь по техкартам», который отвечал
на вопрос «откуда взялись» и почти всегда отвечал на него тавтологией:
из 161 материала у 100 расход равен проданному один к одному, у 109 источник
ровно один, а несколько путей — у одного-единственного. Три строки на экране
сообщали один факт: «на изделие идёт одна штука».

**Норма расхода** говорит то же самое одной строкой — и заодно проверяет
техкарту: у диметикона 8 изделий берут по 200 г, а 12 по 20 г, разница
в десять раз, и увидеть её больше негде.

**Где сидит расход** отвечает на «в чём сидят деньги» — вопрос, который
задают чаще, чем «откуда взялись»: список из пяти изделий с долями вместо
списка из пятидесяти девяти с повторами.
"""

from decimal import Decimal

# Сколько изделий показать в распределении. Пять отвечают на «в чём сидит
# основное», а хвост сворачивается в строку — не отбрасывается: слагаемые
# обязаны складываться в объясняемое число.
TOP_SOURCES = 5

# Норма округляется до шести знаков перед группировкой — ровно до той
# точности, с которой она уходит в ответ и показывается.
#
# Причина не в арифметике Decimal (28 значащих цифр хватает с запасом),
# а в том, что группировка идёт по ключу, а на экран уходит округлённое.
# Техкарта одного изделия задаёт 0.142857, техкарта другого — 1/7; ключи
# разные, обе строки на экране читаются как «0,142857», и человек видит
# две одинаковые нормы вместо одной. Группировать надо по тому, что видно.
_RATE = Decimal("0.000001")


def rates_of(sources: list[dict]) -> list[dict]:
    """Нормы расхода: сколько материала уходит на одно изделие.

    Группируются, а не перечисляются по изделию. У 121 материала из 161
    норма одна на все изделия — и тогда это одна строка «1 шт на изделие,
    16 изделий» вместо списка из шестнадцати одинаковых.

    Изделия с нулевой продажей пропускаются: делить не на что, а норма
    «ноль на ноль» — не факт учёта.
    """
    grouped: dict[Decimal, list[dict]] = {}

    for source in sources:
        sold = source["sold_quantity"]
        if sold <= 0:
            continue
        rate = (source["quantity"] / sold).quantize(_RATE)
        grouped.setdefault(rate, []).append(source)

    rows = [
        {
            "rate": rate,
            "products_count": len(items),
            # Примеры — не весь список: строка должна оставаться строкой.
            # Крупнейшие по расходу, чтобы в примере стояло то, что человек
            # уже видел в распределении рядом.
            "examples": [
                item["name"]
                for item in sorted(items, key=lambda item: -item["quantity"])[:3]
            ],
        }
        for rate, items in grouped.items()
    ]

    # От большей нормы к меньшей: расхождение в техкартах заметно именно
    # сверху списка, где стоит «200 г» против «20 г» ниже.
    rows.sort(key=lambda row: -row["rate"])
    return rows


def distribution(sources: list[dict], total: Decimal) -> dict:
    """Где сидит расход: крупнейшие изделия с долями и свёрнутый хвост.

    Доли считаются от всего расхода материала, поэтому складываются в сто
    процентов, а количества — в объясняемое число. Хвост сворачивается,
    а не отбрасывается: без строки «ещё 34 изделия» показанные слагаемые
    не сходятся с числом строки, и расхождение спишут на расчёт.
    """
    ordered = sorted(sources, key=lambda item: -item["quantity"])
    top = ordered[:TOP_SOURCES]
    rest = ordered[TOP_SOURCES:]

    return {
        "top": [
            {
                "product_id": item["product_id"],
                "name": item["name"],
                "quantity": item["quantity"],
                "share": _share(item["quantity"], total),
            }
            for item in top
        ],
        "rest": (
            {
                "products_count": len(rest),
                "quantity": sum(
                    (item["quantity"] for item in rest), Decimal(0)
                ),
                "share": _share(
                    sum((item["quantity"] for item in rest), Decimal(0)), total
                ),
            }
            if rest
            else None
        ),
    }


def _share(part: Decimal, whole: Decimal) -> Decimal | None:
    """Доля единицы. `None` — делить не на что.

    Своя, а не `core.money.share`: та работает с целыми копейками, а здесь
    количества — `Decimal` с тремя знаками, и приведение к int потеряло бы
    доли грамма, из которых половина расхода и состоит.
    """
    if whole <= 0:
        return None
    return part / whole
