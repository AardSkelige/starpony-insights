"""Линейки товаров: сворачивание наименований в строки, которые о чём-то говорят.

Ошибки здесь тихие вдвойне. Потерянный при группировке товар не роняет
страницу — список просто перестаёт складываться в выручку канала, и разница
читается как потерянные деньги. А выдуманная подпись выглядит достовернее
настоящей: «Кондиционеры» — слово, которого в учёте нет ни у одного товара.
"""

from types import SimpleNamespace

from api.channels.services import families


def product(id, name, article=""):
    return SimpleNamespace(id=id, name=name, article=article)


def entries(*items, revenue=10_000):
    """Товары канала в том виде, в каком их собирает страница."""
    return {
        item.id: {
            "name": item.name,
            "line": families.line_of(item),
            "revenue_kopecks": revenue,
        }
        for item in items
    }


def by_name(rows):
    return {row["name"]: row for row in rows}


def test_line_comes_from_the_article():
    """Линейку задаёт первый сегмент артикула — классификация учёта,
    а не догадка по тексту названия."""
    assert families.line_of(product(1, "Шампунь", "100.011.05")) == "100"
    assert families.line_of(product(2, "Кондиционер", "200.036.50")) == "200"


def test_product_without_an_article_is_its_own_line():
    """Доставка, короб и пробник линейки не образуют: артикула у них нет,
    и объединить их можно было бы только выдумав признак."""
    assert families.line_of(product(7, "Доставка")) != families.line_of(
        product(8, "Картонный короб")
    )


def test_volume_is_read_from_the_name():
    """Объём берётся из конца названия. Единицы перечислены, а не «любое
    слово»: иначе «Кондиционер …Кока-Кола» отдал бы «Кока-Кола» за объём."""
    assert families.volume_of("Кондиционер для гривы и хвоста Кока-Кола 500 мл") == "500 мл"
    assert families.volume_of("Воск для амуниции 150 г") == "150 г"
    assert families.volume_of("Доставка — СДЭК (ПВЗ)") == ""
    # Название из учёта, которым проверка и держится: цифры в конце есть,
    # а объёма в них нет. Возьми регулярное выражение «любое слово» вместо
    # перечня единиц — и коробка получила бы объём «23 в)».
    assert (
        families.volume_of(
            "Картонный короб 8х8х25см (Короб №233-Ц, 80*80*250 мм, Т-23 В)"
        )
        == ""
    )


def test_volumes_do_not_mix():
    """Пол-литровый кондиционер и пятилитровый — две строки.

    Продаются они разным людям и разными деньгами, и «Кондиционер» одной
    строкой теряет ровно то различие, ради которого в список смотрят.
    """
    rows = by_name(
        families.grouped(
            entries(
                product(1, "Кондиционер для гривы и хвоста Табак-Ваниль 500 мл", "200.036.05"),
                product(2, "Кондиционер для гривы и хвоста Кокосовое молоко 500 мл", "200.031.05"),
                product(3, "Кондиционер для гривы и хвоста Табак-Ваниль 5000 мл", "200.036.50"),
                product(4, "Кондиционер для гривы и хвоста Кокосовое молоко 5000 мл", "200.031.50"),
            )
        )
    )

    assert sorted(rows) == ["Кондиционер 500 мл", "Кондиционер 5000 мл"]
    assert rows["Кондиционер 500 мл"]["items_count"] == 2


def test_label_is_short_and_carries_the_volume():
    """Подпись — первое слово названия и объём из него же. Оба факта,
    а не сочинённый термин, и оба читаются с одного взгляда."""
    rows = families.grouped(
        entries(
            product(1, "Кондиционер для гривы и хвоста Табак-Ваниль 500 мл", "200.036.05"),
            product(2, "Кондиционер для гривы и хвоста Кока-Кола 500 мл", "200.030.05"),
        )
    )

    assert rows[0]["name"] == "Кондиционер 500 мл"
    # Полное название не теряется — оно уходит в подсказку.
    assert rows[0]["full_name"] == "Кондиционер для гривы и хвоста 500 мл"


def test_single_product_is_short_too():
    """Одиночный товар подписывается так же коротко: список, где «Кондиционер
    500 мл» соседствует с «Репеллент для лошадей Против насекомых 500 мл»,
    читается как два разных списка."""
    rows = families.grouped(
        entries(product(1, "Репеллент для лошадей Против насекомых 500 мл", "300.002.05"))
    )

    assert rows[0]["name"] == "Репеллент 500 мл"
    assert rows[0]["full_name"] == "Репеллент для лошадей Против насекомых 500 мл"


def test_colliding_labels_get_their_full_names():
    """«Кондиционер 250 мл» — это и для гривы, и для амуниции. Две одинаковые
    строки в списке читаются как ошибка расчёта, поэтому обе разворачиваются."""
    rows = by_name(
        families.grouped(
            entries(
                product(1, "Кондиционер для гривы и хвоста 250 мл", "200.050.25"),
                product(2, "Кондиционер для амуниции 250 мл", "400.002.25"),
            )
        )
    )

    assert sorted(rows) == [
        "Кондиционер для амуниции 250 мл",
        "Кондиционер для гривы и хвоста 250 мл",
    ]


def test_line_without_a_common_beginning_stays_split():
    """У линейки `400` общего начала нет — воск, масло и пенка. Четыре честные
    строки лучше одной с выдуманным именем, поэтому группа не собирается."""
    rows = by_name(
        families.grouped(
            entries(
                product(1, "Воск для амуниции 150 г", "400.003.15"),
                product(2, "Масло для амуниции 250 г", "400.004.25"),
                product(3, "Пенка для очистки амуниции 200 мл", "400.001.20"),
            )
        )
    )

    assert sorted(rows) == ["Воск 150 г", "Масло 250 г", "Пенка 200 мл"]
    assert all(row["items_count"] == 1 for row in rows.values())


def test_two_words_in_common_are_not_a_line():
    """«Кондиционер для» — это и кондиционер для гривы, и кондиционер для
    амуниции. Двух общих слов мало: под такой подписью встретились бы
    разные товары одной линейки."""
    rows = families.grouped(
        {
            1: {"name": "Кондиционер для гривы и хвоста 500 мл", "line": "X", "revenue_kopecks": 100},
            2: {"name": "Кондиционер для амуниции 500 мл", "line": "X", "revenue_kopecks": 100},
        }
    )

    assert len(rows) == 2


def test_variants_are_named_by_revenue():
    """Состав линейки — по убыванию выручки: спрашивают «какой берут»,
    а не «какие бывают»."""
    rows = families.grouped(
        {
            1: {"name": "Шампунь для лошадей белых мастей 500 мл", "line": "100", "revenue_kopecks": 100},
            2: {"name": "Шампунь для лошадей рыжих мастей 500 мл", "line": "100", "revenue_kopecks": 900},
        }
    )

    assert rows[0]["variants"] == ["рыжих мастей", "белых мастей"]


def test_money_survives_the_grouping():
    """Сумма на выходе равна сумме на входе. Потеряйся здесь товар, разница
    выглядела бы потерянными деньгами, и найти её было бы нечем."""
    given = entries(
        product(1, "Шампунь для лошадей белых мастей 500 мл", "100.011.05"),
        product(2, "Шампунь для лошадей вороных мастей 500 мл", "100.012.05"),
        product(3, "Шампунь для лошадей белых мастей 5000 мл", "100.011.50"),
        product(4, "Репеллент для лошадей Против насекомых 500 мл", "300.002.05"),
        product(5, "Доставка"),
    )

    rows = families.grouped(given)

    assert sum(row["revenue_kopecks"] for row in rows) == sum(
        entry["revenue_kopecks"] for entry in given.values()
    )
