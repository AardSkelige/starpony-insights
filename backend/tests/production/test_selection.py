"""Разбор партии из адресной строки: форма, потолки, пустой артикул.

Отдельно от расчёта: здесь проверяется, что доехало и в каком виде,
а не что из этого вышло. Ошибки тут тихие — сломанная строка выглядит
как выбор человека, а урезанная партия считается без единого признака.
"""

import pytest
from rest_framework import serializers

from api.production.services.selection import MAX_LINE_QUANTITY, parse_batch


def test_голый_артикул_означает_посчитай_сам():
    assert parse_batch(["200.040.05"]) == {"200.040.05": None}


def test_артикул_с_количеством_закреплён_руками():
    assert parse_batch(["200.040.05:12"]) == {"200.040.05": 12}


def test_повторы_складываются():
    assert parse_batch(["200.040.05:5", "200.040.05:3"]) == {"200.040.05": 8}


def test_введённое_руками_побеждает_посчитай_сам():
    """Затирать набранное расчётом мы не вправе — в любом порядке."""
    assert parse_batch(["200.040.05", "200.040.05:7"]) == {"200.040.05": 7}
    assert parse_batch(["200.040.05:7", "200.040.05"]) == {"200.040.05": 7}


def test_потолок_считается_после_сложения_повторов():
    """До этого потолок обходился повтором одного артикула.

    `item=A:9999999&item=A:9999999` давало двадцать миллионов в одной
    позиции — вдвое выше объявленного предела, и объявленного зря.
    """
    with pytest.raises(serializers.ValidationError):
        parse_batch([f"200.040.05:{MAX_LINE_QUANTITY}"] * 2)


@pytest.mark.parametrize("item", [" :5", "  :5", " ", "\t:5"])
def test_артикул_из_пробелов_не_проходит(item):
    """Пустой артикул совпал бы с позициями, у которых артикула нет вовсе.

    А это ровно сырьё, которое «Расчёт производства» товаром не считает
    (решение 02.09): материал попал бы в партию как изделие.

    Отвергает его **форма**, а не отдельная проверка: `value.strip()`
    срезает пробелы до разбора, и до двоеточия не остаётся ни знака.
    Проверка на пустоту была бы недостижимой — а недостижимому охраннику
    верят, и он тем опаснее.
    """
    with pytest.raises(serializers.ValidationError):
        parse_batch([item])


@pytest.mark.parametrize(
    "item", ["200.040.05:", ":5", "200.040.05:0", "200.040.05:2.5", "a:1:2"]
)
def test_сломанная_строка_отвергается(item):
    with pytest.raises(serializers.ValidationError):
        parse_batch([item])
