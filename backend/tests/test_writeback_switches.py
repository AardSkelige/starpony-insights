"""У каждого вида обратной записи есть выключатель, заведённый миграцией.

`CLAUDE.md` §6 обещает: «новый вид записи = строка в `WritebackKind` плюс
строка в миграции выключателей; забывчивость ловит тест». Теста при этом
не было — обещание держалось на внимательности, а проверить его нечем
было ровно до того момента, когда выключатель понадобится.

**Выключатель обязан быть виден в админке до поломки.** Выключать приходится
тогда, когда запись уже портит учёт, и в этот момент человеку некогда
догадываться, что строку надо сперва создать кнопкой «Добавить».
"""

import pytest

from core.models import WritebackKind, WritebackSwitch

pytestmark = pytest.mark.django_db


def test_every_kind_has_a_switch_from_migrations():
    """Каждый вид записи заводится миграцией, а не первым прогоном.

    Строка, создаваемая при первом прогоне, появляется **после** того, как
    запись уже что-то сделала. Выключатель, которого в этот момент нет, —
    не выключатель.
    """
    seeded = set(WritebackSwitch.objects.values_list("kind", flat=True))
    missing = set(WritebackKind.values) - seeded

    assert not missing, (
        f"У этих видов записи нет выключателя: {', '.join(sorted(missing))}. "
        f"Заведите строку миграцией — см. `core/migrations/0014` и `0027`."
    )


def test_switches_start_enabled():
    """Умолчание — «работает», и оно обратное реестру страниц.

    Там забывчивость обязана закрывать доступ; здесь отсутствие запрета
    означает «его ещё не выключали», а не «запрещено». Запрет — решение
    человека, а не следствие пустой таблицы.
    """
    assert not WritebackSwitch.objects.filter(enabled=False).exists()
