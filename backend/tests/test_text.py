"""Склонение существительного при числе."""

import pytest

from core.text import with_plural

WORDS = ("материал", "материала", "материалов")


@pytest.mark.parametrize(
    ("count", "expected"),
    [
        (1, "1 материал"),
        (2, "2 материала"),
        (4, "4 материала"),
        (5, "5 материалов"),
        (0, "0 материалов"),
        # Одиннадцать–четырнадцать кончаются на 1–4, но склоняются как «много».
        # Ровно здесь ошибается наивная реализация «по последней цифре».
        (11, "11 материалов"),
        (12, "12 материалов"),
        (14, "14 материалов"),
        (21, "21 материал"),
        (22, "22 материала"),
        (111, "111 материалов"),
        (161, "161 материал"),
    ],
)
def test_declines_by_the_number(count, expected):
    assert with_plural(count, *WORDS) == expected
